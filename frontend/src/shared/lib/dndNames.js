function normalizedRaceLabel(race) {
  const labels = typeof race === 'string' ? [race] : [race?.name, race?.nameEn]
  return labels.filter(Boolean).join(' ').toLocaleLowerCase('ru').replaceAll('ё', 'е').replace(/[-_]+/g, ' ')
}

export function dndNameProfile(race) {
  const label = normalizedRaceLabel(race)
  return PROFILE_DEFINITIONS.find(profile => profile.aliases.some(alias => label.includes(alias))) || FALLBACK_PROFILE
}

export function dndNamePoolSize(race) {
  const profile = dndNameProfile(race)
  return profile.given.length * profile.family.length
}

function randomIndex(length, random) {
  return Math.min(length - 1, Math.max(0, Math.floor(random() * length)))
}

export function randomDndName(race, random = Math.random, excluded = '') {
  const profile = dndNameProfile(race)
  const given = profile.given[randomIndex(profile.given.length, random)]
  let familyIndex = randomIndex(profile.family.length, random)
  let result = `${given} ${profile.family[familyIndex]}`
  if (result === excluded.trim() && profile.family.length > 1) {
    familyIndex = (familyIndex + 1) % profile.family.length
    result = `${given} ${profile.family[familyIndex]}`
  }
  return result
}
