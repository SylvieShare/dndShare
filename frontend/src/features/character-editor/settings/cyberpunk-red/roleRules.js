export function redWorkshop(price, mode = "fabrication") {
  if (!Number.isFinite(price) || price < 0)
    throw new Error("Выберите предмет с ценой");
  const rows = [
    [20, 9, "1 час", 5],
    [50, 13, "6 часов", 20],
    [100, 17, "1 день", 50],
    [500, 21, "1 неделя", 100],
    [1000, 24, "2 недели", 500],
    [5000, 29, "1 месяц", 1000],
  ];
  const row = rows.find((r) => price <= r[0]) || [
    price,
    29,
    `${Math.ceil(price / 10000)} мес.`,
    price / 2,
  ];
  return {
    dv: row[1],
    time: row[2],
    materials: mode === "invention" ? 0 : mode === "upgrade" ? price : row[3],
  };
}
