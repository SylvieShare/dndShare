export function editorHints(tool, dragging) {
  if (tool === "bind-light")
    return [
      "Выберите плитку или объект для привязки света",
      "Esc — отмена привязки",
    ];
  const camera = [
    "Стрелки — камера",
    "Колесо — масштаб",
    "ЛКМ + перенос — камера",
  ];
  if (tool === "decal")
    return [
      "ЛКМ — наложить на поверхность",
      "Cmd/Ctrl + клик — поставить ещё",
      "R — повернуть на 15°",
      "ПКМ/Esc — отмена",
      ...camera,
    ];
  if (tool === "paste")
    return [
      "ЛКМ — вставить участок",
      "Cmd/Ctrl + клик — вставить и продолжить",
      "R — поворот группы",
      "T — отражение плиток",
      "ПКМ — отмена вставки",
      "Esc — отмена вставки",
      ...camera,
    ];
  if (tool === "light")
    return [
      "ЛКМ — поставить источник света",
      "ПКМ — отмена вставки",
      "Esc — отмена вставки",
      ...camera,
    ];
  if (dragging)
    return [
      "ЛКМ — разместить плитку",
      "R — поворот",
      "T — отражение плиток",
      "Cmd/Ctrl + перенос — заполнение",
      "ПКМ — отмена размещения",
      "Esc — отмена размещения",
      ...camera,
    ];
  const action = tool === "object" ? "ЛКМ — поставить объект" : null;
  return [
    action || "Плитка из списка — перетащить",
    "Удержать ½ с + перенос — элемент",
    "R — поворот",
    "T — отражение плиток и существ",
    "Cmd/Ctrl + клик — группа",
    "Cmd/Ctrl + рамка — группа",
    ...camera,
    "ПКМ — вращение камеры",
    "Shift + перенос — вращение",
    "Esc — отмена",
  ];
}
