export function editorHints(tool, dragging) {
  const camera = [
    "Стрелки — камера",
    "Колесо — масштаб",
    "Alt + перенос — сдвиг поля",
  ];
  if (tool === "paste")
    return [
      "ЛКМ — вставить участок",
      "R — поворот группы",
      "ПКМ — отмена вставки",
      "Esc — отмена вставки",
      ...camera,
    ];
  if (dragging)
    return [
      "ЛКМ — разместить плитку",
      "R — поворот",
      "Cmd/Ctrl + перенос — заполнение",
      "ПКМ — отмена размещения",
      "Esc — отмена размещения",
      ...camera,
    ];
  const action = {
    object: "ЛКМ — поставить объект",
    zone: "ЛКМ + перенос — область зоны",
    "zone-brush": "ЛКМ + перенос — клетки зоны",
    "wall-brush": "ЛКМ + перенос — рисовать стены",
  }[tool];
  return [
    action || "Плитка из списка — перетащить",
    "R — поворот",
    "Cmd/Ctrl + клик — группа",
    "Cmd/Ctrl + рамка — группа",
    ...camera,
    "ПКМ — вращение камеры",
    "Shift + перенос — вращение",
    "Esc — отмена",
  ];
}
