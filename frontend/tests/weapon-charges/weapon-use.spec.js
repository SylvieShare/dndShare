 await page.setViewportSize({ width, height: 844 }); await page.goto(url)
 await openRoll(page)
 const minus = page.getByRole('button', { name: 'Помеха', exact: true })
 const plus = page.getByRole('button', { name: 'Преимущество', exact: true })
 await expect(minus).toHaveAttribute('aria-pressed', 'false')
 await expect(plus).toHaveAttribute('aria-pressed', 'false')
 await expect.poll(() => plus.evaluate(right => {
  const leftBox = right.previousElementSibling.getBoundingClientRect()
  const rightBox = right.getBoundingClientRect()
  return Math.abs(leftBox.top - rightBox.top) < 2 && leftBox.right < rightBox.left && rightBox.right <= innerWidth
 })).toBe(true)
 await minus.click()
 await expect(minus).toHaveAttribute('aria-pressed', 'true')
 await plus.click()
 await expect(minus).toHaveAttribute('aria-pressed', 'false')
 await expect(plus).toHaveAttribute('aria-pressed', 'true')
 await page.evaluate(() => { window.testRolls = [3, 17]; window.attackEffects = [{ mode: 'disadvantage' }] })
 await submitRoll(page).click()
 expect(await page.evaluate(() => window.attackResults.at(-1))).toMatchObject({ rollMode: 'advantage', total: 22 })
 await openRoll(page)
 await expect(minus).toHaveAttribute('aria-pressed', 'false')
 await expect(plus).toHaveAttribute('aria-pressed', 'false')
 await plus.click()
 await plus.click()
 await expect(plus).toHaveAttribute('aria-pressed', 'false')
 await submitRoll(page).click()
 expect(await page.evaluate(() => window.attackResults.at(-1))).toMatchObject({ rollMode: 'disadvantage', total: 8 })
