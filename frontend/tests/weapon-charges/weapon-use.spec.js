import { test, expect } from '@playwright/test'
import { attackMetric, closeWeaponRoll, openWeaponRoll, rollDialog, submitRoll, weaponCard } from './roll-actions'
test.use({ reducedMotion: 'reduce' })

const url = '/tests/weapon-charges/weapon-use.html'
const current = page => page.evaluate(() => window.ctx.values.weapon[0].params.magic)
const title = 'Метательное копьё молнии'
const openRoll = (page, scope) => openWeaponRoll(page, title, scope)
async function attack(page, natural = 10) {
 await page.evaluate(n => window.natural = n, natural)
 await openRoll(page)
 await expect(page.getByRole('combobox')).toHaveCount(0)
 await page.getByLabel('Метнуть молнией', { exact: true }).click()
 expect((await current(page)).remaining).toBe(1)
 await submitRoll(page).click()
}
for (const width of [1280, 390]) test(`direct damage menu separates the target from the flat line (${width})`, async ({ page }) => {
 await page.setViewportSize({ width, height: 844 }); await page.goto(url)
 await expect(page.getByRole('button', { name: 'Бросить на атаку', exact: true })).toHaveCount(0)
 await openRoll(page, 'damage')
 await page.getByRole('button', { name: 'Метнуть молнией', exact: true }).click()
 await page.getByRole('button', { name: 'Критическое попадание', exact: true }).click()
 expect((await current(page)).remaining).toBe(1)
 const target = submitRoll(page, 'damage')
 const line = rollDialog(page).getByRole('button', { name: 'Урон по линии', exact: true })
 const targetBox = await target.boundingBox(), lineBox = await line.boundingBox()
 expect(lineBox.y).toBeGreaterThan(targetBox.y + targetBox.height)
 await expect(rollDialog(page).getByRole('group', { name: 'Урон', exact: true }).getByRole('separator')).toHaveCount(1)
 await line.click()
 expect(await page.evaluate(() => window.damageRolls)).toEqual(['4d6{Молния|#ff0}'])
 expect(await page.evaluate(() => window.attackResults.length)).toBe(0)
 expect((await current(page)).remaining).toBe(0)
 await page.reload()
 await weaponCard(page, title).getByRole('button', { name: 'Настроить урон: Урон по линии', exact: true }).click()
 await expect(rollDialog(page).getByRole('alert')).toBeVisible()
 await expect(submitRoll(page, 'damage')).toBeDisabled()
 await closeWeaponRoll(page)
 await openRoll(page, 'damage')
 await expect(rollDialog(page).getByRole('button', { name: 'Урон по линии', exact: true })).toBeDisabled()
 await page.getByRole('button', { name: 'Метнуть молнией', exact: true }).click()
 await submitRoll(page, 'damage').click()
 expect(await page.evaluate(() => window.damageRolls)).toEqual(['1d6{Колющий}+3{Колющий}+4d6{Молния|#ff0}'])
 expect((await current(page)).remaining).toBe(0)
})
for (const width of [1280, 390]) test(`line is flat, rolls inline and survives reload or a missed target (${width})`, async ({ page }) => {
 await page.setViewportSize({ width, height: 844 }); await page.goto(url)
 await attack(page)
 await weaponCard(page, title).locator('summary').filter({ hasText: 'Метнуть молнией' }).click()
 expect((await current(page)).remaining).toBe(0)
 await expect(weaponCard(page, title).locator('.weapon-use-stage').getByText('Урон по цели', { exact: true })).toHaveCount(0)
 await expect(page.getByText(/Бросок атаки:|Уже списано:/)).toHaveCount(0)
 await expect(page.locator('.item-use-panel .item-use-panel, .item-use-panel .base-tile')).toHaveCount(0)
 const button = await page.getByRole('button', { name: 'Бросить урон', exact: true }).boundingBox()
 const formula = await page.getByLabel('Итоговая формула урона').boundingBox()
 expect(button.x + button.width).toBeLessThan(formula.x)
 await page.getByRole('button', { name: 'Бросить урон', exact: true }).dblclick()
 await expect(page.getByLabel('Результат броска: 15')).toBeVisible()
 await expect(page.getByLabel('Результат броска: 15').getByRole('img')).toHaveCount(4)
 await expect(page.getByText('= 15', { exact: true })).toBeVisible()
 await expect(page.getByText(/^При успехе:/)).toHaveCount(0)
 expect(await page.evaluate(() => window.damageRolls)).toEqual(['4d6{Молния|#ff0}'])
 await page.reload()
 await weaponCard(page, title).locator('summary').filter({ hasText: 'Метнуть молнией' }).click()
 await expect(page.getByLabel('Результат броска: 15')).toBeVisible()
 await page.evaluate(() => window.ctx.updateValues({ items: { sections: [{ items: window.ctx.values.weapon }] }, weapon: [] }))
 await page.reload()
 await expect(page.getByLabel('Результат броска: 15')).toBeVisible()
 await page.getByRole('button', { name: 'Завершить применение', exact: true }).click()
 await page.getByRole('button', { name: 'Завершить', exact: true }).click()
 expect(await page.evaluate(() => window.ctx.values.items.sections[0].items[0].params.magic)).toMatchObject({ remaining: 0, weapon_use: { status: 'completed' } })
})
test('hit addition lives in the damage dialog and pays once; readers have no controls', async ({ page }) => {
 await page.goto(url); await attack(page, 20)
 await page.evaluate(() => window.ctx.ownerMode = false)
 await expect(page.getByRole('button', { name: 'Бросить урон', exact: true })).toHaveCount(0)
 await expect(attackMetric(weaponCard(page, title))).toHaveCount(0)
 await page.evaluate(() => window.ctx.ownerMode = true)
 await openRoll(page, 'damage')
 await page.getByLabel('Метнуть молнией', { exact: true }).click()
 await page.getByLabel('Критическое попадание', { exact: true }).click()
 await expect(rollDialog(page).getByLabel('Состав урона')).toContainText('8')
 await submitRoll(page, 'damage').click()
 expect((await current(page)).weapon_use.steps[1].status).toBe('rolled')
 expect((await current(page)).remaining).toBe(0)
 await weaponCard(page, title).locator('summary').filter({ hasText: 'Метнуть молнией' }).click()
 await page.getByRole('button', { name: 'Бросить урон', exact: true }).click()
 expect(await page.evaluate(() => window.damageRolls)).toEqual(['2d6{Колющий}+3{Колющий}+8d6{Молния|#ff0}', '4d6{Молния|#ff0}'])
 await openRoll(page, 'damage')
 await expect(page.getByLabel('Метнуть молнией', { exact: true })).toHaveCount(0)
 await closeWeaponRoll(page)
 await page.getByRole('button', { name: 'Завершить применение', exact: true }).click()
 await openRoll(page)
 await expect(page.getByLabel('Метнуть молнией', { exact: true })).toBeDisabled()
 await submitRoll(page).click()
 expect(await page.evaluate(() => window.attackResults.length)).toBe(2)
 expect((await current(page)).remaining).toBe(0)
})
