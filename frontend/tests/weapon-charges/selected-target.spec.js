import { test, expect } from '@playwright/test'
import { closeWeaponRoll, openWeaponRoll, rollDialog, submitRoll, weaponCard } from './roll-actions'
test.use({ reducedMotion: 'reduce' })

const url = '/tests/weapon-charges/selected-target.html'
async function declare(page, name = 'Орк') {
 const summary = weaponCard(page, title).locator('summary').filter({ hasText: 'Заклятый враг' })
 if (await summary.getAttribute('aria-expanded') === 'false') await summary.click()
 await page.getByLabel('Имя противника', { exact: true }).fill(name)
 await page.getByRole('button', { name: 'Объявить цель', exact: true }).click()
 await expect(page.getByText(name, { exact: true })).toBeVisible()
}
const title = 'Лук клятвы'
const openRoll = (page, scope) => openWeaponRoll(page, title, scope)
for (const width of [1280, 390]) test(`target shares selection between attacks and damage in their respective roll dialogs (${width})`, async ({ page }) => {
 await page.setViewportSize({ width, height: 844 }); await page.goto(url); await declare(page)
 await openRoll(page)
 const target = rollDialog(page).getByRole('button', { name: 'По выбранной цели: Орк', exact: true })
 await expect(target).toHaveAttribute('aria-pressed', 'true')
 await expect(rollDialog(page).getByRole('group', { name: 'Способ атаки' }).getByRole('button', { name: 'Метнуть' })).toBeVisible()
 await expect(rollDialog(page).getByRole('group', { name: 'Дополнительные эффекты' }).getByRole('button', { name: 'По выбранной цели: Орк' })).toBeVisible()
 await submitRoll(page).click()
 expect(await page.evaluate(() => window.attackResults.at(-1).rollMode)).toBe('advantage')
 await openRoll(page, 'damage')
 await expect(target).toHaveAttribute('aria-pressed', 'true'); await expect(target).toHaveAccessibleDescription('+3к6')
 await page.getByLabel('Критическое попадание', { exact: true }).click()
 await expect(target).toHaveAccessibleDescription('+6к6')
 await submitRoll(page, 'damage').click()
 expect(await page.evaluate(() => window.damageRolls.at(-1))).toBe('2d8{Колющий}+3{Колющий}+6d6{Колющий}')
 await openRoll(page, 'damage'); await target.click()
 await closeWeaponRoll(page); await page.reload()
 await openRoll(page); await expect(target).toHaveAttribute('aria-pressed', 'false')
 await submitRoll(page).click()
 expect(await page.evaluate(() => window.attackResults.at(-1).rollMode)).toBe('normal')
 await openWeaponRoll(page, 'Меч')
 await submitRoll(page).click()
 expect(await page.evaluate(() => window.attackResults.at(-1).rollMode)).toBe('disadvantage')
})
test('death waits for an explicit dawn even without resources; readers cannot change the target', async ({ page }) => {
 await page.goto(url); await declare(page)
 await page.evaluate(() => window.ctx.ownerMode = false)
 await expect(page.getByText('Орк', { exact: true })).toBeVisible()
 await expect(page.getByRole('button', { name: 'Враг погиб', exact: true })).toHaveCount(0)
 await page.evaluate(() => window.ctx.ownerMode = true)
 await page.getByRole('button', { name: 'Враг погиб', exact: true }).click()
 await page.getByRole('button', { name: 'Подтвердить', exact: true }).click()
 await expect(page.getByRole('textbox', { name: 'Имя противника' })).toHaveCount(0)
 await openWeaponRoll(page, 'Меч')
 await submitRoll(page).click()
 expect(await page.evaluate(() => window.attackResults.at(-1).rollMode)).toBe('normal')
 await page.getByRole('button', { name: 'Рассвет', exact: true }).click()
 await page.getByRole('button', { name: 'Встретить рассвет', exact: true }).click()
 await page.getByRole('button', { name: 'Готово', exact: true }).click()
 await declare(page, 'Дракон')
 await expect(page.getByText('Осталось рассветов: 7')).toBeVisible()
})
test('editor hides optional dice and validates the target duration', async ({ page }) => {
 await page.goto(`${url}?editor`)
 await expect(page.getByLabel('Добавляет урон по цели', { exact: true })).toBeChecked()
 await page.getByLabel('Добавляет урон по цели', { exact: true }).click()
 expect(await page.evaluate(() => window.editorData.selected_target.damage)).toBeUndefined()
 await page.evaluate(() => window.editorData.selected_target.duration_dawns = 0)
 await expect.poll(() => page.evaluate(() => window.editorError)).toContain('длительность 1–100')
})
