import { test, expect } from '@playwright/test'
const url = '/tests/weapon-charges/weapon-panels.html'
for (const width of [1280,390]) test(`only concrete mechanics host charges, and presses stay on the main row (${width})`, async ({ page }) => {
 await page.setViewportSize({ width, height: 1000 }); await page.goto(url)
 const javelin = page.getByTestId('javelin'), mace = page.getByTestId('mace'), plain = page.getByTestId('plain')
 await expect(javelin).toHaveClass(/base-tile/)
 const properties = await javelin.locator('.weapon-metrics__properties').boundingBox()
 const mechanics = await javelin.locator('.weapon-item-mechanics').boundingBox()
 expect(mechanics.x).toBeCloseTo(properties.x, 0)
 expect(mechanics.width).toBeCloseTo(properties.width, 0)
 const damage = await javelin.locator('.weapon-metrics__damage').boundingBox()
 expect(mechanics.y - properties.y - properties.height).toBeCloseTo(properties.y - damage.y - damage.height, 0)
 for (const tile of [javelin.locator('.weapon-metrics__properties'), javelin.locator('.item-mechanic-panel')]) {
  expect(await tile.evaluate(el => parseFloat(getComputedStyle(el).borderBottomLeftRadius))).toBeGreaterThan(0)
 }
 await expect(javelin.locator('.item-mechanic-panel')).toHaveCount(1)
 await expect(mace.locator('.item-mechanic-panel')).toHaveCount(1)
 await expect(plain.locator('.item-mechanic-panel')).toHaveCount(0)
 await expect(page.getByText(/Просто описание копья|Общее описание магического оружия/)).toHaveCount(0)
 await expect(page.locator('.item-mechanic-panel--resource')).toHaveCount(0)
 for (const details of await page.locator('details').all()) await expect(details).toHaveJSProperty('open',false)
 await expect(javelin.getByRole('group',{name:/из/})).toHaveAttribute('aria-label',/1 из 1/)
 await expect(mace.getByRole('group',{name:/из/})).toHaveAttribute('aria-label',/3 из 3/)
 await mace.getByRole('button',{name:'Заряд 3',exact:true}).click()
 await expect(mace.getByRole('group',{name:/из/})).toHaveAttribute('aria-label',/2 из 3/)
 await expect(mace.locator('details')).toHaveJSProperty('open',false)
 await expect(page.getByRole('menu')).toHaveCount(0)
 const summary = javelin.locator('summary')
 await summary.click(); await expect(javelin.getByText('Урон по линии',{exact:true})).toBeVisible()
 await expect.poll(() => javelin.locator('details').evaluate(element => element.getAnimations().length)).toBe(0)
 await expect(javelin.getByRole('button',{name:'Бросить на атаку',exact:true})).toHaveCount(0)
 await javelin.locator('.w-name').click()
 const general = page.getByRole('menu')
 await expect(general.getByRole('menuitem', {name:'Изменить'})).toBeVisible()
 await expect(general.getByText(/Бросить на (атаку|урон)/)).toHaveCount(0)
 await page.keyboard.press('Escape')
 await javelin.getByRole('button', {name:'Настроить бросок урона'}).click()
 await expect(page.getByRole('menu')).toHaveCount(1)
 await expect(page.getByRole('menu', {name:'Урон', exact:true})).toBeVisible()
 await expect(page.getByRole('switch', {name:'Критическое попадание'})).toBeVisible()
 await page.keyboard.press('Escape')
 await javelin.getByRole('button',{name:'Настроить бросок атаки',exact:true}).click()
 await expect(page.getByRole('menu')).toHaveCount(1)
 await expect(page.getByRole('menu', { name: 'Атака', exact:true })).toBeVisible()
 await expect(page.getByRole('menuitem', {name:'Изменить'})).toHaveCount(0)
 await page.getByRole('switch',{name:'Метнуть молнией',exact:true}).click()
 await page.getByRole('menuitem',{name:'Бросить на атаку',exact:true}).last().click()
 await expect(javelin.getByRole('group',{name:/из/})).toHaveAttribute('aria-label',/0 из 1/)
 await expect(javelin.locator('details')).toHaveJSProperty('open',true)
 await expect(javelin.getByRole('button',{name:'Бросить урон',exact:true})).toBeVisible()
 const scale = locator => locator.evaluate(element => new DOMMatrixReadOnly(getComputedStyle(element).transform).a)
 const box = await mace.locator('summary').boundingBox()
 await page.mouse.move(box.x+20,box.y+box.height/2); await page.mouse.down()
 expect(await scale(mace)).toBe(1); await expect.poll(() => scale(mace.locator('.ram-custom-trigger'))).toBe(1)
 await page.mouse.up()
 await expect.poll(() => mace.locator('details').evaluate(element => element.getAnimations().length)).toBe(0)
 const row = await mace.locator('.w-card-main').boundingBox()
 await page.mouse.move(row.x+20,row.y+row.height/2); await page.mouse.down()
 await expect.poll(() => scale(mace.locator('.ram-custom-trigger'))).toBe(1)
 expect(await scale(mace)).toBe(1); await page.mouse.up(); await page.keyboard.press('Escape')
 const first = await javelin.boundingBox(), second = await mace.boundingBox()
 expect(second.y - first.y - first.height).toBeGreaterThanOrEqual(8)
 await page.mouse.click(second.x + 20, second.y - 4)
 await expect(page.getByRole('menu')).toHaveCount(0)
 await page.evaluate(() => window.ctx.ownerMode=false)
 await expect(mace.getByRole('button',{name:'Заряд 1',exact:true})).toBeDisabled()
})

test('weapon menus configure live card formulas without spending or duplicating their preview', async ({ page }) => {
 await page.goto('/tests/weapon-charges/weapon-panels.html?rollSources')
 await page.locator('.weapon-metrics__attack').first().click()
 const menu = page.getByRole('menu')
 await expect(menu.getByText('Метательное копьё молнии · Атака')).toBeVisible()
 await expect(menu.locator('.weapon-roll-heading small')).toHaveText('Сила')
 const throwing = menu.getByRole('button', { name: 'Метнуть', exact: true })
 await expect(throwing).toHaveAccessibleDescription('30/120 фт.')
 await throwing.click()
 await expect(throwing).toHaveAttribute('aria-pressed', 'true')
 await expect(menu.locator('.weapon-formula')).toHaveCount(0)
 const card = page.locator('.w-card').first()
 await expect(card.locator('.weapon-metrics__attack .system-die')).toHaveCount(1)
 await page.keyboard.press('Escape')
 await page.locator('.weapon-metrics__damage').first().click()
 const damage = card.locator('.weapon-metrics__damage').first()
 const crit = menu.getByRole('switch', { name: 'Критическое попадание' })
 await crit.click()
 await expect(damage.locator('.weapon-damage__count')).toHaveText(['2×'])
 await expect(damage.locator('.weapon-damage__addend').filter({ hasText: 'Ярость' }).getByRole('img', { name: 'd6: 6', exact: true })).toBeVisible()
 await crit.click()
 await menu.getByRole('switch', { name: 'Метнуть молнией', exact: true }).click()
 await expect(card.locator('[data-damage-key="lightning_throw:target"]')).toHaveCount(0)
 await expect(card.locator('.weapon-metrics__alternative')).toHaveCount(1)
 await expect(damage.locator('.weapon-damage__source')).toHaveText(['Оружие', 'Сила', 'Ярость', 'Метнуть молнией'])
 await expect(damage.locator('.weapon-damage__flat')).toHaveText(['2', '2'])
 await expect(damage.locator('.weapon-damage__count')).toHaveText(['4×'])
 await menu.getByRole('switch', { name: 'Критическое попадание' }).click()
 await expect(damage.locator('.weapon-damage__count')).toHaveText(['2×', '8×'])
 await page.keyboard.press('Escape')
 await expect(damage.locator('.weapon-damage__source')).toHaveText(['Оружие', 'Сила', 'Ярость'])
 expect(await page.evaluate(() => window.ctx.values.weapon[0].params.magic.remaining)).toBe(1)
})
