import { expect, test } from '@playwright/test'

test('registration, password change and logout persist through the real API and cookies', async ({ page }) => {
  const errors = []
  page.on('pageerror', error => errors.push(error.message))
  await page.goto('/')
  await page.getByRole('button', { name: 'Войти', exact: true }).click()
  const login = page.getByRole('dialog', { name: 'Вход', exact: true })
  await login.getByRole('button', { name: 'Регистрация', exact: true }).click()
  const registration = page.getByRole('dialog', { name: 'Регистрация', exact: true })
  await registration.getByPlaceholder('Придумайте логин').fill('browser-smoke')
  await registration.getByPlaceholder('Придумайте пароль').fill('initial-pass')
  await registration.getByPlaceholder('Повторите пароль', { exact: true }).fill('initial-pass')
  await registration.getByRole('button', { name: 'Создать аккаунт', exact: true }).click()
  await expect(registration).toHaveCount(0)
  await page.goto('/account')
  await expect(page.getByRole('heading', { name: 'browser-smoke', exact: true })).toBeVisible()
  await page.getByLabel('Текущий пароль', { exact: true }).fill('initial-pass')
  await page.getByLabel('Новый пароль', { exact: true }).fill('changed-pass')
  await page.getByLabel('Повторите новый пароль', { exact: true }).fill('changed-pass')
  await page.getByRole('button', { name: 'Изменить пароль', exact: true }).click()
  await expect(page.getByRole('status')).toContainText('Пароль')
  await page.reload()
  await expect(page.getByRole('heading', { name: 'browser-smoke', exact: true })).toBeVisible()
  const invalid = await page.request.post('/api/user/auth', { data: { login: 'browser-smoke', password: 'initial-pass' } })
  expect(invalid.ok()).toBe(true)
  expect((await invalid.json()).auth).toBe(false)
  const valid = await page.request.post('/api/user/auth', { data: { login: 'browser-smoke', password: 'changed-pass' } })
  expect((await valid.json()).auth).toBe(true)
  await page.goto('/')
  await page.getByRole('button', { name: 'browser-smoke', exact: true }).click()
  await page.getByRole('menuitem', { name: 'Выйти', exact: true }).click()
  await expect(page.getByRole('button', { name: 'Войти', exact: true })).toBeVisible()
  await page.reload()
  expect((await (await page.request.get('/api/user/checkAuth')).json()).auth).toBe(false)
  expect(errors).toEqual([])
})
