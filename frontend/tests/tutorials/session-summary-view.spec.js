import { test,expect } from '@playwright/test'
import { openRosterActions, rosterSelectionFixture } from './fixtures/session-roster.js'
import { spacingTokens } from '../../src/app/design-tokens.js'

for(const width of [390,834,1440])test(`shared sidebar and scene summaries with persistent actions at ${width}`,async({page},info)=>{
  test.setTimeout(60000)
  const api=await rosterSelectionFixture(page,width)
  const wolf=api.encounter().combatants.find(row=>row.uid==='wolf')
  wolf.effectInstances.push({uid:'wolf-poison',effect_id:702})
  api.participants[0].data.values.states=[...structuredClone(wolf.effectInstances)]
  api.encounter().combatants.push({...structuredClone(wolf),uid:'owl',markerLetter:'B',override:{name:'Сова',hp:8,ac:12},effectInstances:[]})
  await page.reload()
  const sidebar=page.locator('aside.map-sidebar'),nav=page.getByRole('navigation',{name:'Боковые вкладки сессии'})
  if((await sidebar.getAttribute('class')).includes('map-sidebar--collapsed'))await nav.getByRole('button',{name:'Игроки',exact:true}).click()
  const toolbar=sidebar.locator('.session-sidebar-header-controls'),heading=sidebar.locator('.map-sidebar-heading'),players=sidebar.locator('[data-tutorial="session-players"]')
  await expect(toolbar.getByRole('button', { name: 'Действия', exact: true })).toBeDisabled()
  await expect(sidebar.locator('.map-sidebar-panel')).toHaveCSS('transform','none')
  await expect(heading.locator('strong')).toHaveCSS('transform','none')
  const titleOffset=()=>heading.evaluate(node=>node.querySelector('strong').getBoundingClientRect().left-node.getBoundingClientRect().left)
  const titleLeft=await titleOffset()
  await nav.getByRole('button',{name:'Запас',exact:true}).click()
  await expect.poll(titleOffset).toBeCloseTo(titleLeft,0)
  const reserve=sidebar.getByRole('region',{name:'Запас существ',exact:true})
  await expect(toolbar.getByRole('button', { name: 'Действия', exact: true })).toBeDisabled()
  await expect(reserve.getByRole('button',{name:'Создать упрощённое существо',exact:true})).toHaveCount(0)
  const topEdge = 'polygon(0% calc(var(--spacing-small) * 0.5),100% calc(var(--spacing-small) * 0.5),'
  const paint = row => row.evaluate(node => node.style.getPropertyValue('--roster-paint-clip'))
  const reserveTiles = reserve.locator('.enc-row-tile')
  expect(await paint(reserveTiles.first())).toContain(topEdge)
  expect(await paint(reserveTiles.nth(1))).not.toContain(topEdge)
  await expect(reserve.locator('.enc-row-shell').nth(1).locator('.workspace-row-divider')).toHaveCount(1)
  await expect(reserve.locator('.enc-row-shell').nth(1)).toHaveCSS('border-top-width','0px')
  const marker=reserve.locator('.npc-marker').first()
  await expect(marker).toHaveCSS('backdrop-filter','blur(4px)')
  expect(await marker.evaluate(n=>getComputedStyle(n).backgroundColor)).toMatch(/rgba\(.+,\s*0\.\d+\)|color\(.+\/\s*0\.\d+\)/)
  const add=heading.getByRole('button',{name:'Добавить существо',exact:true})
  await add.click()
  const addMenu=page.getByRole('menu',{name:'Добавить существо',exact:true})
  await expect(addMenu.getByRole('menuitem',{name:'Создать упрощённое существо',exact:true})).toBeVisible()
  await expect(addMenu.getByRole('menuitem',{name:'Добавить из справочника',exact:true})).toBeVisible()
  await addMenu.getByRole('menuitem',{name:'Создать упрощённое существо',exact:true}).click()
  const create=page.getByRole('dialog',{name:'Своё существо',exact:true})
  await create.getByPlaceholder('Гоблин-вожак').fill('Лиса')
  await create.getByRole('button',{name:'Добавить',exact:true}).click()
  await expect(reserve.getByText('Лиса',{exact:true})).toBeVisible()
  await add.click();await addMenu.getByRole('menuitem',{name:'Добавить из справочника',exact:true}).click()
  await expect(page.getByRole('dialog',{name:'Бестиарий',exact:true})).toBeVisible()
  await page.keyboard.press('Escape')
  await expect(page.locator('.ram-popover[aria-label="Добавить существо"]')).toHaveCount(0)
  await info.attach(`reserve-summary-${width}`,{body:await sidebar.screenshot({animations:'disabled'}),contentType:'image/png'})
  await reserve.getByRole('checkbox',{name:'Выбрать: Волк',exact:true}).click()
  const challenge = (await openRosterActions(page, toolbar)).getByRole('menuitem', { name: 'Провести испытание' })
  await challenge.click()
  await expect(page.getByText('Испытание выбранным', { exact: true })).toBeVisible()
  await expect(page.locator('.ecm-heading')).toContainText('1 участник')
  await page.keyboard.press('Escape')
  await expect(page.getByText('Испытание выбранным', { exact: true })).toHaveCount(0)
  await page.keyboard.press('Escape')
  await page.getByRole('button',{name:/Открыть бой/}).click()
  await (await openRosterActions(page, toolbar)).getByRole('menuitem',{name:/^Добавить на сцену:/}).click()
  await nav.getByRole('button',{name:'Игроки',exact:true}).click()
  expect(await paint(players.locator('.p-card-menu').first())).toContain(topEdge)
  await players.getByRole('checkbox',{name:'Выбрать: Лира',exact:true}).click()
  await (await openRosterActions(page, toolbar)).getByRole('menuitem',{name:/^Добавить на сцену:/}).click()
  const controls=page.locator('.enc-secondary')
  const leftSummary=toolbar.getByRole('group',{name:'Выбрано по видам'})
  const rightSummary=controls.getByRole('group',{name:'Выбрано по видам'})
  await expect(leftSummary.getByRole('img')).toHaveCount(2)
  await expect(rightSummary).toHaveCount(0)
  const mountedSummary = await leftSummary.elementHandle()
  await heading.getByRole('button',{name:'Свернуть боковую панель',exact:true}).click()
  await expect(leftSummary).toHaveCount(0)
  await expect(rightSummary.getByRole('img')).toHaveCount(2)
  expect(await rightSummary.evaluate((node, mounted) => node === mounted, mountedSummary)).toBe(true)
  await controls.getByRole('button',{name:'Сбросить выбор',exact:true}).click()
  await expect(rightSummary).toHaveText('Никто не выбран')
  const workspace=page.locator('.enc-wrap--workspace'),scene=workspace.locator('.enc-content')
  const npc=scene.locator('[data-encounter-uid="wolf"]'),player=scene.locator('[data-encounter-uid="p-1"]')
  await expect(npc.locator('.session-npc-tile.session-roster-tile')).toHaveCount(1)
  await expect(player.locator('.session-player-tile.session-roster-tile')).toHaveCount(1)
  await expect(scene.locator('.creature-tile,input[type=checkbox]')).toHaveCount(0)
  const selectScene = scene.getByRole('checkbox', { name: 'Выбрать всех на сцене', exact: true })
  await selectScene.click()
  await expect(selectScene).toBeChecked()
  await expect(rightSummary.getByRole('img')).toHaveCount(2)
  await selectScene.click()
  await expect(rightSummary).toHaveText('Никто не выбран')
  await expect(npc.locator('.health-readout')).toHaveText('15/20')
  await expect(player.locator('.health-readout')).toHaveText('18/24')
  for(const row of [npc,player]){
    const blessing=row.getByRole('button',{name:'Благословение',exact:true})
    const poison=row.getByRole('button',{name:'Отравление',exact:true})
    await expect(blessing).toContainText('2 раунда')
    await expect(row.locator('.item-icon').first()).toHaveCSS('width','56px')
    await expect(row.locator('.session-roster-tile[aria-current="true"]')).toHaveCount(0)
    const statusArea=row.getByRole('group',{name:'Эффекты и состояния'})
    await expect(statusArea.locator('.dsov-row')).toHaveCSS('flex-wrap','wrap')
    const [first,second,area]=await Promise.all([blessing.boundingBox(),poison.boundingBox(),statusArea.boundingBox()])
    expect(first.width).toBeLessThanOrEqual(area.width)
    expect(second.width).toBeLessThanOrEqual(area.width)
    expect(second.x+second.width).toBeLessThanOrEqual(area.x+area.width+1)
    if(width===390)expect(second.y).toBeGreaterThan(first.y)
    const gap = await statusArea.locator('.dsov-row').evaluate(node => parseFloat(getComputedStyle(node).columnGap))
    if (first.width + second.width + gap <= area.width + .5) expect(second.y).toBeCloseTo(first.y, 0)
    else expect(second.y).toBeGreaterThanOrEqual(first.y + first.height - .5)
  }
  const positions=await scene.evaluate((n,pad)=>({left:n.getBoundingClientRect().left,expected:n.closest('.enc-wrap').getBoundingClientRect().left+pad}),spacingTokens.page)
  expect(positions.left).toBeCloseTo(positions.expected,0)
  for(const row of [npc,player]){
    await row.locator('.heading-health').click()
    await expect(page.getByRole('dialog',{name:'Хиты',exact:true})).toBeVisible()
    await page.keyboard.press('Escape')
  }
  await scene.getByRole('checkbox',{name:'Выбрать: Волк',exact:true}).click()
  await expect(npc.getByRole('checkbox')).toBeChecked()
  await controls.getByRole('button',{name:'Сбросить выбор',exact:true}).click()
  await info.attach(`scene-summary-${width}`,{body:await page.screenshot({animations:'disabled'}),contentType:'image/png'})
  if(width===834){
    api.participants[0].data.values.hp.current=0
    await page.reload()
    await expect(page.locator('.enc-content [data-encounter-uid="p-1"] .ds-row')).toContainText('Спасброски')
    await expect(page.locator('.enc-content [data-encounter-uid="p-1"]').getByRole('button',{name:'Воскресить игрока',exact:true})).toBeVisible()
  }
  expect(api.errors).toEqual([]);expect(api.warnings).toEqual([])
})


test('challenge results appear on sidebar player and NPC tiles before combat', async ({ page }) => {
  const api = await rosterSelectionFixture(page, 390)
  await page.emulateMedia({ reducedMotion: 'reduce' })
  const requests = []
  await page.route('**/api/sessions/test/d20', async route => {
    requests.push(route.request().postDataJSON())
    await route.fulfill({ json: { rolls: [12], karmic: false } })
  })
  const sidebar = page.locator('aside.map-sidebar')
  const navigation = sidebar.getByRole('navigation')
  const toolbar = sidebar.locator('.session-sidebar-header-controls')
  await navigation.getByRole('button', { name: 'Запас', exact: true }).click()
  const wolf = sidebar.locator('[data-encounter-uid="wolf"]')
  await wolf.getByRole('checkbox').click()
  await navigation.getByRole('button', { name: 'Игроки', exact: true }).click()
  const player = sidebar.locator('.p-card-menu').filter({ hasText: 'Лира' })
  await player.getByRole('checkbox', { name: 'Выбрать: Лира', exact: true }).click()
  const actions = await openRosterActions(page, toolbar)
  const experience = actions.getByRole('menuitem', { name: 'Добавить опыт: 1' })
  const damage = actions.getByRole('menuitem', { name: 'Нанести урон: 2' })
  await expect(experience.locator('.action-target-portrait')).toHaveAttribute('title', 'Лира')
  await expect(experience.locator('.action-target-count')).toHaveText('1')
  await expect(damage.locator('.action-target-portrait')).toHaveCount(2)
  await expect(damage.locator('.action-target-count')).toHaveText('2')
  await actions.getByRole('menuitem', { name: 'Провести испытание' }).click()
  await page.getByRole('button', { name: 'Бросить выбранным', exact: true }).click()
  await expect(actions).toHaveCount(0)
  await expect(player.locator('.enc-row-result .ecr-total')).toHaveText('14')
  await player.getByRole('button', { name: 'Скрыть результат броска', exact: true }).click({ modifiers: ['Control'] })
  await expect(player.locator('.enc-row-result')).toHaveCount(0)
  await expect(player.getByRole('checkbox')).toBeChecked()
  await player.getByRole('button', { name: 'Показать результат броска', exact: true }).click()
  await expect(player.locator('.enc-row-result')).toBeVisible()
  await navigation.getByRole('button', { name: 'Запас', exact: true }).click()
  await expect(wolf.locator('.enc-row-result .ecr-total')).toHaveText('12')
  expect(requests).toHaveLength(2)
  expect(api.encounter().active).toBe(false)
  expect(api.encounter().combatants.every(row => row.position === 'reserve')).toBe(true)
  await toolbar.getByRole('button', { name: 'Убрать испытание', exact: true }).click()
  await expect(sidebar.locator('.enc-row-result')).toHaveCount(0)
  await expect(toolbar.getByRole('button', { name: 'Убрать испытание', exact: true })).toHaveCount(0)
})
