import { expect, test } from '@playwright/test'
import { sessionMapControls } from './fixtures/session-map-controls.js'

test('session maps and their broadcast have separate entry points without a map header', async ({ page }, info) => {
  await page.setViewportSize({ width: 932, height: 704 })
  await page.emulateMedia({ reducedMotion: 'reduce' })
  const { broadcasts } = await sessionMapControls(page)
  const sidebar = page.getByRole('navigation', { name: 'Боковые вкладки сессии' })
  const mapsTab = sidebar.getByRole('button', { name: 'Карты', exact: true })
  const header = page.locator('.chapter-toolbar')
  const screenButton = header.getByRole('button', { name: 'Экран показа', exact: true })
  const screen = page.getByRole('dialog', { name: 'Экран показа', exact: true })
  const controls = screen.getByRole('toolbar', { name: 'Трансляция карты' })
  const list = page.getByRole('region', { name: 'Карты сессии', exact: true })
  const pickMap = name => list.getByRole('button', { name: new RegExp(`^${name}(?: В эфире)?$`) })
  const canvas = page.locator('.map-canvas-surface')
  await expect(canvas).toBeVisible()
  await expect(page.locator('.session-map-tabs-header')).toHaveCount(0)
  const headerBounds = await header.boundingBox()
  expect((await canvas.boundingBox()).y).toBeCloseTo(headerBounds.y + headerBounds.height, 0)

  for (const width of [430, 1440, 932]) {
    await page.setViewportSize({ width, height: 704 })
    const labels = await sidebar.getByRole('button').evaluateAll(buttons => buttons.map(button => button.getAttribute('aria-label')))
    expect(labels.indexOf('Карты')).toBeGreaterThan(labels.indexOf('Запас'))
    expect(labels.indexOf('Карты')).toBeLessThan(labels.indexOf('Плитки'))
    await expect(screenButton).toBeVisible()
  }

  await mapsTab.click()
  await expect(page.locator('.session-sidebar-header-controls')).toHaveCount(0)
  await expect(pickMap('Зал')).toHaveAttribute('aria-pressed', 'true')
  await expect(pickMap('Зал')).toContainText('В эфире')
  await list.screenshot({ path: info.outputPath('session-maps-list.png') })
  await list.getByRole('button', { name: 'Добавить карту', exact: true }).click()
  const add = page.getByRole('dialog', { name: 'Добавить карту', exact: true })
  await expect(add.getByRole('button', { name: 'Добавить 2D карту' })).toBeVisible()
  await add.getByRole('button', { name: 'Закрыть выбор карты' }).click()
  await list.getByRole('button', { name: 'Переименовать карту «Склеп»' }).click()
  const rename = page.getByRole('dialog', { name: 'Карта сессии', exact: true })
  await expect(rename.getByRole('textbox', { name: 'Название карты сессии' })).toHaveValue('Склеп')
  await rename.getByRole('button', { name: 'Отмена', exact: true }).click()

  await pickMap('Склеп').click()
  await expect(list).not.toBeVisible()
  expect(broadcasts).toEqual([])
  await screenButton.click()
  await expect(controls.getByText('В эфире: Зал')).toBeVisible()
  await expect(screen.getByRole('link', { name: 'Открыть экран карты' })).toHaveAttribute('href', '/map-screen/TEST')
  await expect(controls.getByRole('button', { name: 'Транслировать карту «Склеп»' })).toBeEnabled()
  await screen.screenshot({ path: info.outputPath('session-map-broadcast.png') })
  await controls.getByRole('button', { name: 'Перейти к виду камеры трансляции' }).click()
  await expect(screen).toHaveCount(0)
  expect(broadcasts).toEqual([])

  await mapsTab.click()
  await expect(pickMap('Зал')).toHaveAttribute('aria-pressed', 'true')
  await pickMap('Склеп').click()
  await screenButton.click()
  await controls.getByRole('button', { name: 'Транслировать карту «Склеп»' }).click()
  await expect.poll(() => broadcasts.at(-1)).toMatchObject({ mapId: 'crypt', visible: true })
  await controls.getByRole('button', { name: 'На карту', exact: true }).click()
  const creatures = page.getByRole('dialog', { name: 'На карту', exact: true })
  await expect(creatures).toBeVisible()
  await expect(creatures.getByRole('button', { name: 'Лира', exact: true })).toBeVisible()
  await page.keyboard.press('Escape')
  await expect(creatures).toHaveCount(0)
  await expect(screen).toBeVisible()
  await controls.getByRole('button', { name: 'Остановить трансляцию', exact: true }).click()
  await expect.poll(() => broadcasts.at(-1)).toMatchObject({ mapId: 'crypt', visible: false })

  await screenButton.click()
  await mapsTab.click()
  await pickMap('План').click()
  await screenButton.click()
  await controls.getByRole('button', { name: 'Калибровка экрана', exact: true }).click()
  const calibration = page.getByRole('dialog', { name: 'Экран карты', exact: true })
  await calibration.getByRole('button', { name: 'Поворот стола: 0°', exact: true }).click()
  await expect(calibration.getByRole('button', { name: 'Поворот стола: 90°', exact: true })).toBeVisible()
  await expect.poll(() => broadcasts.at(-1)).toMatchObject({ camera: { rotation: 90 } })
})
