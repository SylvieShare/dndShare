import { test, expect } from '@playwright/test'
import { sessionLayout } from './fixtures/session-layout.js'
import { layoutTokens } from '../../src/app/design-tokens.js'

for (const width of [390,834,1440]) test(`session player header and chapter safe area at ${width}`, async ({page},info) => {
  page.on('pageerror',error=>{throw error})
  await page.setViewportSize({width,height:900})
  await sessionLayout(page)
  const sidebar=page.locator('aside.map-sidebar'),nav=page.getByRole('navigation',{name:'Боковые вкладки сессии'})
  if ((await sidebar.getAttribute('class')).includes('map-sidebar--collapsed')) await nav.getByRole('button',{name:'Игроки',exact:true}).click()
  const heading=sidebar.locator('.map-sidebar-heading'),add=heading.getByRole('button',{name:'Действия с игроками',exact:true})
  await expect(add).toBeVisible()
  const offset=await add.evaluate(button=>{const a=button.getBoundingClientRect(),b=button.querySelector('svg').getBoundingClientRect();return {x:b.x+b.width/2-a.x-a.width/2,y:b.y+b.height/2-a.y-a.height/2}})
  expect(Math.abs(offset.x)).toBeLessThan(.5)
  expect(Math.abs(offset.y)).toBeLessThan(.5)
  await add.click()
  const menu=page.getByRole('menu',{name:'Действия с игроками',exact:true})
  await expect(menu).toContainText('Присоединить своего персонажа')
  await expect(menu).toContainText('Создать персонажа')
  await expect(menu).toContainText('Скопировать код приглашения')
  await expect(menu).toContainText('Скопировать ссылку приглашения')
  await page.keyboard.press('Escape')
  const cards=sidebar.locator('.p-card')
  await expect(cards).toHaveCount(2)
  await add.hover()
  await expect(cards.first()).toHaveCSS('background-color','rgba(0, 0, 0, 0)')
  await expect(sidebar.locator('.participants-list > .p-card-menu').nth(1)).toHaveCSS('border-top-width','1px')
  const statuses=cards.first().locator('.dsov-effect')
  await expect(statuses).toHaveCount(2)
  const first=await statuses.nth(0).boundingBox(),second=await statuses.nth(1).boundingBox()
  expect(second.y).toBeGreaterThanOrEqual(first.y+first.height)
  await expect(statuses.first().locator('.item-icon')).toHaveCSS('width','40px')
  await info.attach('players',{body:await sidebar.screenshot(),contentType:'image/png'})
  await heading.getByRole('button',{name:'Свернуть боковую панель',exact:true}).click()
  const chapter=page.locator('.nested-graph-node[data-graph-node-id="12"]')
  await chapter.dblclick()
  const ancestor=page.locator('.session-graph-ancestor--chapter')
  await expect(ancestor).toBeVisible()
  const chrome=await page.locator('.chapter-toolbar').boundingBox()
  expect((await ancestor.boundingBox()).y).toBeGreaterThanOrEqual(chrome.y+chrome.height+13)
  await info.attach('selected-chapter',{body:await page.screenshot(),contentType:'image/png'})
  await page.locator('.nested-graph-node[data-graph-node-id="31"]').dblclick()
  const scene=page.locator('.session-graph-ancestor--scene')
  await expect(scene).toBeAttached()
  await scene.scrollIntoViewIfNeeded()
  await expect(scene).toBeInViewport()
  await scene.click()
  await expect(page.locator('.scene-graph-menu')).toBeVisible()
  await page.keyboard.press('Escape')
  const returnOffset=await page.evaluate(async()=>{
    const old=document.querySelector('.session-graph-ancestor--scene').getBoundingClientRect()
    document.querySelector('.session-graph-back').click()
    return new Promise(resolve=>requestAnimationFrame(()=>{
      const next=document.querySelector('.nested-graph-node[data-graph-node-id="31"]').getBoundingClientRect()
      resolve({x:next.x-old.x,y:next.y-old.y})
    }))
  })
  expect(Math.abs(returnOffset.x)).toBeLessThan(2)
  expect(Math.abs(returnOffset.y)).toBeLessThan(2)
  await expect(page.locator('.session-graph-canvas')).toHaveAttribute('data-level','scenes')
})

test('selected chapter follows the single live sidebar width in both directions',async({page})=>{
  await page.setViewportSize({width:1440,height:900})
  await page.emulateMedia({reducedMotion:'no-preference'})
  await sessionLayout(page)
  await page.locator('.nested-graph-node[data-graph-node-id="12"]').dblclick()
  await expect(page.locator('.session-graph-ancestor--chapter')).toBeVisible()
  for(const close of [true,false]) {
    await page.evaluate(()=>{
      window.sidebarSamples=[]
      const sidebar=document.querySelector('aside.map-sidebar'),ancestor=document.querySelector('.session-graph-ancestors')
      const observer=new ResizeObserver(()=>queueMicrotask(()=>window.sidebarSamples.push({width:sidebar.getBoundingClientRect().width,gap:ancestor.getBoundingClientRect().left-sidebar.getBoundingClientRect().right})))
      observer.observe(sidebar)
      window.stopSidebarSampling=()=>observer.disconnect()
    })
    if(close)await page.locator('.map-sidebar-heading').getByRole('button',{name:'Свернуть боковую панель',exact:true}).click()
    else await page.getByRole('navigation',{name:'Боковые вкладки сессии'}).getByRole('button',{name:'Игроки',exact:true}).click()
    await expect(page.locator('aside.map-sidebar')).toHaveCSS('width',`${layoutTokens[close?'map-rail':'map-sidebar']}px`)
    const samples=await page.evaluate(()=>{window.stopSidebarSampling();return window.sidebarSamples})
    expect(samples.length).toBeGreaterThan(3)
    expect(Math.max(...samples.map(s=>Math.abs(s.gap-20)))).toBeLessThan(2)
  }
})
