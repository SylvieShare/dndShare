import { expect, test } from '@playwright/test'

for (const width of [475, 704, 1440]) test(`spell roll windows reset their drafts and keep the card stable at ${width}`, async ({ page }, info) => {
  await page.setViewportSize({ width, height: 932 })
  const errors = []
  page.on('pageerror', error => errors.push(error.message))
  await page.goto('/tests/tutorials/fixtures/spell-rolls.html')
  const row = page.locator('.spell-row').filter({ hasText: 'Леденящее прикосновение' })
  const original = await row.innerText()
  await row.getByRole('button', { name: 'Настроить бросок атаки', exact: true }).click()
  const attack = page.getByRole('dialog', { name: 'Леденящее прикосновение · Атака', exact: true })
  await expect(attack.locator('.character-roll-dialog')).toBeVisible()
  await expect(page.getByRole('menu')).toHaveCount(0)
  const preview = attack.locator('.spell-roll-preview')
  await expect(preview.getByRole('img', { name: 'd20: 20', exact: true })).toBeVisible()
  await expect(preview.getByRole('img', { name: 'd4: 4', exact: true })).toBeVisible()
  await expect(attack.getByRole('button', { name: 'Помеха', exact: true })).toHaveAttribute('aria-pressed', 'true')
  await attack.getByRole('button', { name: 'Преимущество', exact: true }).click()
  await expect(preview).toContainText('Преимущество')
  await attack.getByRole('button', { name: 'Благословение', exact: true }).click()
  await expect(preview.getByRole('img', { name: 'd4: 4', exact: true })).toHaveCount(0)
  expect(await row.innerText()).toBe(original)
  expect(await attack.evaluate(node => node.scrollWidth <= node.clientWidth)).toBe(true)
  await attack.screenshot({ path: info.outputPath('spell-attack.png'), animations: 'disabled' })
  await page.keyboard.press('Escape')
  await expect(attack).toHaveCount(0)
  await row.getByRole('button', { name: 'Настроить бросок атаки', exact: true }).click()
  await expect(attack.getByRole('button', { name: 'Помеха', exact: true })).toHaveAttribute('aria-pressed', 'true')
  await expect(attack.getByRole('button', { name: 'Благословение', exact: true })).toHaveAttribute('aria-pressed', 'true')
  await attack.getByRole('button', { name: 'Закрыть окно броска', exact: true }).click()
  await row.getByRole('button', { name: 'Настроить бросок урона', exact: true }).click()
  const damage = page.getByRole('dialog', { name: 'Леденящее прикосновение · Урон', exact: true })
  const critical = damage.getByRole('switch', { name: 'Критическое попадание', exact: true })
  await critical.click()
  await expect(damage.locator('.spell-roll-preview .dd-count')).toHaveText('4')
  expect(await row.innerText()).toBe(original)
  expect(await damage.evaluate(node => node.scrollWidth <= node.clientWidth)).toBe(true)
  await damage.screenshot({ path: info.outputPath('spell-damage.png'), animations: 'disabled' })
  await page.keyboard.press('Escape')
  await row.getByRole('button', { name: 'Настроить бросок урона', exact: true }).click()
  await expect(critical).toHaveAttribute('aria-checked', 'false')
  await expect(damage.locator('.spell-roll-preview .dd-count')).toHaveText('2')
  await page.keyboard.press('Escape')
  await row.locator('.sp-name').click()
  const action = page.getByRole('menuitem', { name: 'Бросить на атаку', exact: true })
  await expect(action).toHaveAttribute('aria-haspopup', 'dialog')
  await action.click()
  await expect(attack).toBeVisible()
  await expect(page.getByRole('menu')).toHaveCount(0)
  await page.keyboard.press('Escape')
  expect(await page.evaluate(() => ({ rolls: window.rolls, writes: window.writes, events: window.events }))).toEqual({ rolls: [], writes: [], events: [] })
  expect(errors).toEqual([])
})
