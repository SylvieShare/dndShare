import { test, expect } from '@playwright/test'
for (const mobile of [false, true]) test(`participant menu and Ctrl selection ${mobile ? 'mobile' : 'desktop'}`, async ({ page }) => {
  page.on('pageerror', error => { throw error })
  await page.setViewportSize(mobile ? { width: 390, height: 844 } : { width: 1200, height: 900 })
  await page.emulateMedia({ reducedMotion: 'reduce' })
  await page.goto('/tests/tutorials/fixtures/participant-controls.html')
  const card = page.locator('.p-card')
  await expect(card).not.toContainText('Эльф')
  await expect(card).not.toContainText('Плут')
  await expect(card.getByLabel('Инициатива')).toHaveCount(0)
  await expect(card.locator('.ecc-ac')).toHaveCount(0)
  await expect(card.locator('.heading-armor-value')).toHaveText('12')
  await expect(card.locator('.heading-metric')).toHaveText(['16','18'])
  await expect(card.locator('.health-readout')).toHaveText('18/24')
  const avatar = await card.locator('.portrait').boundingBox(), health = await card.locator('.heading-health').boundingBox()
  expect(health.x).toBeGreaterThan(avatar.x + avatar.width)
  const tile = await card.boundingBox()
  expect(health.x + health.width).toBeLessThanOrEqual(tile.x + tile.width)
  await card.locator('.identity strong').click({ modifiers: ['Meta'] })
  await expect(page.locator('.p-card-menu')).toBeChecked()
  await expect(page.getByText('Открыть лист', { exact: true })).not.toBeVisible()
  await page.locator('.p-card-menu').click({ modifiers: ['Control'] })
  await expect(page.locator('.p-card-menu')).not.toBeChecked()
  await page.locator('.p-card-menu').click({ modifiers: ['Control'] })
  await expect(page.locator('.p-card-menu')).toBeChecked()
  expect(await page.evaluate(() => window.controls.state.drags)).toBe(0)
  await page.evaluate(()=>{window.controls.state.selecting=false;window.controls.state.selected=false})
  await card.locator('.identity strong').click()
  await expect(page.getByRole('menu').locator('.participant-stats')).toHaveCount(0)
  await page.getByText('Инициатива', { exact: true }).click()
  await page.getByText('Бросить инициативу', { exact: true }).click()
  expect(await page.evaluate(() => window.controls.player.initiative)).toBe(17)
  await page.keyboard.press('Escape')
  await page.evaluate(() => { window.controls.state.drags = 0 })
  const npc = page.locator('.enc-row')
  await expect(npc.locator('.ram-trigger')).not.toBeVisible()
  const npcBox = await npc.boundingBox(), avatarBox = await npc.locator('.enc-avatar').boundingBox(), acBox = await npc.locator('.heading-armor').boundingBox()
  expect(avatarBox.height).toBe(avatar.height)
  expect(acBox.x).toBeGreaterThanOrEqual(avatarBox.x + avatarBox.width)
  await expect(page.locator('input[type=checkbox]')).toHaveCount(0)
  await npc.focus()
  await page.keyboard.press('Enter')
  await expect(page.getByText('История урона и эффектов', { exact: true })).toBeVisible()
  const menu = page.getByRole('menu').filter({ hasText: 'История урона и эффектов' })
  await expect(menu).toBeVisible()
  await expect.poll(async () => (await menu.boundingBox()).y).toBeCloseTo(npcBox.y + npcBox.height + 6, 0)
  const menuBox = await menu.boundingBox()
  expect(menuBox.x).toBeCloseTo(Math.max(8, npcBox.x + npcBox.width - menuBox.width), 0)
  await page.keyboard.press('Escape')
  await npc.locator('.enc-avatar').click()
  await expect(menu).toBeVisible()
  await expect.poll(async () => (await menu.boundingBox()).y).toBeCloseTo(npcBox.y + npcBox.height + 6, 0)
  await npc.locator('.enc-avatar').click()
  await expect(menu).not.toBeVisible()
  await npc.focus()
  await page.keyboard.press('Space')
  await expect(menu).toBeVisible()
  await expect.poll(async () => (await menu.boundingBox()).y).toBeCloseTo(npcBox.y + npcBox.height + 6, 0)
  await page.keyboard.press('Escape')
  await page.evaluate(() => { window.controls.state.drags = 0 })
  await npc.locator('.identity strong').click({ modifiers: ['Meta'] })
  await expect(page.locator('.enc-row-shell')).toBeChecked()
  await page.locator('.enc-row-shell').click({ modifiers: ['Control'] })
  await expect(page.locator('.enc-row-shell')).not.toBeChecked()
  expect(await page.evaluate(() => window.controls.state.drags)).toBe(0)
  await page.evaluate(() => { window.controls.state.npcSelecting=false; window.controls.state.challenge = true })
  await expect(page.locator('.enc-row-result')).toBeVisible()
  await expect(page.locator('.enc-row-roll-overlay')).toHaveCSS('transform', 'none')
  await expect(page.locator('.enc-row-result .ecr-title')).toContainText('Спасбросок')
  const resultBox = await page.locator('.enc-row-result').boundingBox(), rowWithResult = await page.locator('.enc-row-shell').boundingBox()
  expect(resultBox.x + resultBox.width).toBeLessThanOrEqual(rowWithResult.x + rowWithResult.width)
  if (!mobile) expect(rowWithResult.height).toBe(npcBox.height)
  await page.evaluate(() => { window.controls.encounter.encounter.active = true })
  await card.locator('.identity strong').click()
  await expect(page.getByText('Инициатива', { exact: true })).not.toBeVisible()
  await expect(card.getByLabel('Подготовленная инициатива: 17')).toBeVisible()
  await page.getByText('Отправить в бой', { exact: true }).click()
  await page.getByText('В бой', { exact: true }).click()
  expect(await page.evaluate(() => window.controls.player.position)).toBe('combat')
  expect(await page.evaluate(() => window.controls.player.initiative)).toBe(17)
  await expect(card.getByLabel('Подготовленная инициатива: 17')).toHaveCount(0)
})

for (const mobile of [false, true]) test(`combat creature menu anchors to its tile ${mobile ? 'mobile' : 'desktop'}`, async ({ page }) => {
  page.on('pageerror', error => { throw error })
  await page.setViewportSize(mobile ? { width: 390, height: 844 } : { width: 1200, height: 900 })
  await page.emulateMedia({ reducedMotion: 'reduce' })
  await page.goto('/tests/tutorials/fixtures/participant-controls.html')
  await page.evaluate(() => { window.controls.state.npcSection = 'combat' })
  const tile = page.locator('.enc-row')
  const menu = page.getByRole('menu', { name: 'Действия существа' })
  await tile.locator('.enc-avatar').click()
  await expect(menu).toBeVisible()
  const tileBox = await tile.boundingBox()
  await expect.poll(async () => (await menu.boundingBox()).y).toBeCloseTo(tileBox.y + tileBox.height + 6, 0)
  const menuBox = await menu.boundingBox()
  expect(menuBox.x).toBeCloseTo(Math.max(8, tileBox.x + tileBox.width - menuBox.width), 0)
  await expect(menu.getByText('В запас', { exact: true })).toBeVisible()
  await page.keyboard.press('Escape')
  await expect(menu).not.toBeVisible()

  await tile.evaluate(node => {
    node.closest('.enc-combat-layout').style.transform = 'none'
    Object.assign(node.closest('.enc-row-shell').style, { position: 'fixed', bottom: '20px', left: '20px', right: '20px' })
  })
  await tile.focus()
  await page.keyboard.press('Enter')
  await expect(menu).toBeVisible()
  const bottomTileBox = await tile.boundingBox()
  await expect.poll(async () => {
    const box = await menu.boundingBox()
    return box.y + box.height
  }).toBeCloseTo(bottomTileBox.y - 6, 0)
  await expect(menu.getByText('Копировать', { exact: true })).toBeVisible()
  await menu.getByText('Копировать', { exact: true }).click()
  const copies = page.locator('.ram-clone-form')
  await expect(copies).toBeVisible()
  await page.keyboard.press('Escape')
  await expect(copies).not.toBeVisible()
  await expect(menu).toBeVisible()
  await page.keyboard.press('Escape')
  await expect(menu).not.toBeVisible()
})

for (const mobile of [false, true]) test(`NPC relation is optional and edited through menu ${mobile ? 'mobile' : 'desktop'}`, async ({ page }) => {
  await page.setViewportSize(mobile ? { width: 390, height: 844 } : { width: 1200, height: 900 })
  await page.goto('/tests/tutorials/fixtures/participant-controls.html')
  const tile = page.locator('.enc-row')
  await expect(tile).not.toHaveAttribute('data-relation')
  for (const [label, value] of [['Враг', 'enemy'], ['Союзник', 'ally'], ['Приспешник', 'minion'], ['Нейтрал', 'neutral']]) {
    await tile.locator('.identity strong').click()
    await page.getByRole('menu', { name: 'Действия существа', exact: true }).getByText('Отношение', { exact: true }).click()
    await page.getByRole('menuitem', { name: label, exact: true }).click()
    await expect(tile).toHaveAttribute('data-relation', value)
    await expect(tile).toHaveAttribute('aria-description', `Отношение: ${label.toUpperCase()}`)
    expect(await page.evaluate(() => window.controls.npc.side)).toBe(value)
    await page.keyboard.press('Escape')
  }
  await tile.locator('.identity strong').click()
  await page.getByRole('menu', { name: 'Действия существа', exact: true }).getByText('Отношение', { exact: true }).click()
  await page.getByText('Убрать тег', { exact: true }).click()
  await expect(tile).not.toHaveAttribute('data-relation')
  expect(await page.evaluate(() => Object.hasOwn(window.controls.npc, 'side'))).toBe(false)
})

test('NPC conditions and applied effects use the same icon menus as player tiles', async ({ page }) => {
  page.on('pageerror', error => { throw error })
  await page.goto('/tests/tutorials/fixtures/participant-controls.html')
  await page.evaluate(() => {
    window.controls.npc.states = [702]
    window.controls.npc.effectInstances = [{ uid: 'npc-bless', effect_id: 701, params: { level: 1 }, duration: { kind: 'minutes', value: 1 } }]
  })
  const tile = page.locator('.enc-row')
  const icons = tile.getByLabel('Эффекты и состояния')
  await expect(icons.getByRole('button')).toHaveCount(2)
  const blessing = icons.getByRole('button', { name: 'Благословение', exact: true })
  await blessing.click()
  await page.getByRole('menuitem', { name: 'Повысить уровень', exact: true }).click()
  expect(await page.evaluate(() => window.controls.npc.effectInstances[0].params.level)).toBe(2)
  await blessing.click()
  await page.getByRole('button', { name: 'Убрать', exact: true }).click()
  await expect(blessing).toHaveCount(0)
  const poison = icons.getByRole('button', { name: 'Отравление', exact: true })
  await poison.hover()
  await expect(page.locator('.itt-desc')).toContainText('Помеха')
  await poison.click()
  await expect(page.getByRole('button', { name: 'Изменить длительность', exact: true })).toHaveCount(0)
  await page.getByRole('button', { name: 'Убрать', exact: true }).click()
  await expect(icons).toHaveCount(0)
  expect(await page.evaluate(() => window.controls.npc.states)).toEqual([])
  expect(await page.evaluate(() => window.controls.state.drags)).toBe(0)
  await expect(tile.getByRole('checkbox')).toHaveCount(0)
})
