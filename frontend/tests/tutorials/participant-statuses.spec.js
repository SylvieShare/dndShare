import { test, expect } from '@playwright/test'

for (const mobile of [false, true]) test(`participant status icons ${mobile ? 'mobile' : 'desktop'}`, async ({ page }) => {
  page.on('pageerror', error => { throw error })
  await page.setViewportSize(mobile ? { width: 390, height: 844 } : { width: 1200, height: 900 })
  await page.emulateMedia({ reducedMotion: 'reduce' })
  await page.goto('/tests/tutorials/fixtures/participant-controls.html')
  const card = page.locator('.p-card')
  await expect(card.getByText('состояния:', { exact: true })).toHaveCount(0)
  await page.evaluate(() => {
    window.controls.participant.data.values.states = [
      { uid: 'bless', effect_id: 701, params: { level: 1 }, duration: { kind: 'minutes', value: 1 }, concentration: true },
      { uid: 'poison', effect_id: 702, duration: { kind: 'manual' } },
    ]
  })
  const statuses = card.getByLabel('Эффекты и состояния')
  const blessing = statuses.getByRole('button', { name: 'Благословение', exact: true })
  const poison = statuses.getByRole('button', { name: 'Отравление', exact: true })
  await expect(blessing).toBeVisible()
  await expect(poison).toBeVisible()
  await expect(statuses).toHaveText('')
  await expect(statuses.locator('.item-icon')).toHaveCount(2)
  expect((await blessing.locator('.item-icon').boundingBox()).width).toBe(32)
  expect((await blessing.locator('.item-icon').boundingBox()).height).toBe(32)
  const tile = await card.boundingBox(), checkbox = await card.getByRole('checkbox').boundingBox()
  const icons = await statuses.boundingBox(), avatar = await card.locator('.p-avatar').boundingBox(), stats = await card.locator('.participant-stats').boundingBox()
  expect(tile.height).toBe(112)
  expect(checkbox.y + checkbox.height / 2).toBeCloseTo(tile.y + tile.height / 2, 1)
  const column = await card.locator('.p-info').boundingBox()
  expect(icons.x).toBeCloseTo(column.x, 1)
  expect(icons.x).toBeGreaterThanOrEqual(avatar.x + avatar.width)
  const label = card.getByText('состояния:', { exact: true })
  await expect(label).toBeVisible()
  const labelBox = await label.boundingBox()
  expect(labelBox.x).toBeCloseTo(avatar.x, 1)
  expect(labelBox.x + labelBox.width).toBeLessThanOrEqual(icons.x)
  expect(labelBox.y + labelBox.height / 2).toBeCloseTo(icons.y + icons.height / 2, 1)
  expect(icons.y).toBeGreaterThanOrEqual(Math.max(avatar.y + avatar.height, stats.y + stats.height))
  await page.evaluate(() => { window.controls.state.combat = false })
  const normalTile = await card.boundingBox(), normalIcons = await statuses.boundingBox()
  expect(normalTile.height).toBe(112)
  expect(tile.width - normalTile.width).toBe(45)
  expect(normalIcons.width).toBeCloseTo(icons.width, 1)
  await page.evaluate(() => { window.controls.state.combat = true })
  await blessing.hover()
  await expect(page.locator('.itt-title')).toHaveText('Благословение')
  await expect(page.locator('.itt-desc')).toContainText('1d4')
  await poison.focus()
  await expect(page.locator('.itt-title')).toHaveText('Отравление')
  await expect(page.locator('.itt-desc')).toContainText('Помеха')
  await blessing.click()
  let menu = page.getByRole('menu', { name: 'Действия: Благословение', exact: true })
  await expect(menu).toBeVisible()
  await expect(menu.getByText('Изменить длительность', { exact: true })).toBeVisible()
  await expect(menu.getByText('Повысить уровень', { exact: true })).toBeVisible()
  await expect(menu.getByText('Убрать', { exact: true })).toBeVisible()
  await menu.getByText('Посмотреть', { exact: true }).click()
  let modal = page.getByRole('dialog', { name: 'Благословение', exact: true })
  await expect(modal).toBeVisible()
  await expect(modal).toContainText('Добавьте к броскам атаки и спасброскам 1d4.')
  await expect(page.getByRole('menu')).toHaveCount(0)
  expect(await page.evaluate(() => window.controls.state.drags)).toBe(0)
  await expect(card.getByRole('checkbox')).not.toBeChecked()
  await modal.getByRole('button', { name: 'Закрыть', exact: true }).click()
  await expect(modal).toHaveCount(0)
  await poison.click({ modifiers: ['Meta'] })
  menu = page.getByRole('menu', { name: 'Действия: Отравление', exact: true })
  await expect(menu.getByText('Повторить спасбросок', { exact: false })).toBeVisible()
  await menu.getByText('Посмотреть', { exact: true }).click()
  modal = page.getByRole('dialog', { name: 'Отравление', exact: true })
  await expect(modal).toBeVisible()
  await expect(card.getByRole('checkbox')).not.toBeChecked()
  await modal.getByRole('button', { name: 'Закрыть', exact: true }).click()
  await expect(modal).toHaveCount(0)
  await blessing.focus()
  await page.keyboard.press('Enter')
  menu = page.getByRole('menu', { name: 'Действия: Благословение', exact: true })
  await expect(menu).toBeVisible()
  await menu.getByText('Посмотреть', { exact: true }).click()
  modal = page.getByRole('dialog', { name: 'Благословение', exact: true })
  await expect(modal).toBeVisible()
  await modal.getByRole('button', { name: 'Закрыть', exact: true }).click()
  await expect(modal).toHaveCount(0)
  await blessing.click()
  menu = page.getByRole('menu', { name: 'Действия: Благословение', exact: true })
  await menu.getByText('Повысить уровень', { exact: true }).click()
  await expect.poll(() => page.evaluate(() => window.controls.participant.data.values.states.find(row => row.uid === 'bless').params.level)).toBe(2)
  await blessing.click()
  await menu.getByText('Понизить уровень', { exact: true }).click()
  await expect.poll(() => page.evaluate(() => window.controls.participant.data.values.states.find(row => row.uid === 'bless').params.level)).toBe(1)
  await blessing.click()
  await menu.getByText('Изменить длительность', { exact: true }).click()
  const duration = page.getByRole('dialog', { name: 'Длительность: Благословение', exact: true })
  await expect(duration).toBeVisible()
  await duration.getByLabel('Когда заканчивается', { exact: true }).selectOption('rounds')
  await duration.getByLabel('Количество', { exact: true }).fill('5')
  await duration.getByRole('button', { name: 'Сохранить', exact: true }).click()
  await expect(duration).toHaveCount(0)
  expect(await page.evaluate(() => window.controls.participant.data.values.states.find(row => row.uid === 'bless').duration)).toEqual({ kind: 'rounds', value: 5 })
  await poison.click()
  menu = page.getByRole('menu', { name: 'Действия: Отравление', exact: true })
  await menu.getByText('Убрать', { exact: true }).click()
  await expect(poison).toHaveCount(0)
  expect(await page.evaluate(() => window.controls.participant.data.values.states.map(row => row.uid))).toEqual(['bless'])
  const writes = await page.evaluate(() => window.controls.writes)
  expect(writes).toHaveLength(4)
  expect(writes.every(packet => packet.patches.every(patch => patch.path[0] === 'values' && patch.path[1] === 'states'))).toBe(true)
  expect(await page.evaluate(() => window.controls.participant.version)).toBe(5)
  await page.evaluate(() => {
    window.controls.participant.data.values.name = 'Варвар '.repeat(15)
    window.controls.participant.data.values.states = Array.from({ length: 20 }, (_, i) => ({ uid: `effect-${i}`, effect_id: 701 }))
  })
  await expect(statuses.getByRole('button')).toHaveCount(20)
  expect((await card.boundingBox()).width).toBeCloseTo(tile.width, 1)
  expect(await statuses.locator('.dsov-row').evaluate(node => node.scrollWidth > node.clientWidth)).toBe(true)
  const info = await card.locator('.p-info').boundingBox(), hp = await card.locator('.hp-row').boundingBox()
  expect(hp.x + hp.width).toBeLessThanOrEqual(info.x + info.width + .5)
  await page.evaluate(() => { window.controls.state.rejectStatusSave = true })
  await statuses.getByRole('button', { name: 'Благословение', exact: true }).first().click()
  await page.getByRole('menu', { name: 'Действия: Благословение', exact: true }).getByText('Убрать', { exact: true }).click()
  const rejected = page.getByRole('dialog', { name: 'Не удалось сохранить эффект', exact: true })
  await expect(rejected).toBeVisible()
  await expect(rejected).toContainText('Нет прав на изменение персонажа')
  expect(await page.evaluate(() => window.controls.participant.data.values.states.length)).toBe(20)
  expect(await page.evaluate(() => window.controls.participant.version)).toBe(5)
  await rejected.getByRole('button', { name: 'Закрыть', exact: true }).click()
  await page.evaluate(() => { window.controls.state.compact = true })
  await expect(card.locator('.p-statuses-area')).not.toBeVisible()
  await expect(card.locator('.p-statuses-area')).toHaveAttribute('inert', '')
  await expect(card.getByRole('button', { name: 'Благословение', exact: true })).toHaveCount(0)
  expect((await card.boundingBox()).height).toBe(48)
  await page.evaluate(() => { window.controls.state.compact = false; window.controls.state.dm = false })
  await expect(card.locator('.p-statuses-area')).toHaveCount(0)
  await page.evaluate(() => { window.controls.state.dm = true; window.controls.participant.data.values.states = [] })
  await expect(card.locator('.p-statuses-area')).toHaveCount(0)
  expect((await card.boundingBox()).height).toBe(72)
  await expect(label).toHaveCount(0)
})
