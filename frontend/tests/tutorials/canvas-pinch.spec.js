import { test, expect } from '@playwright/test'
import { sessionLayout } from './fixtures/session-layout.js'
import { setup, open } from '../global-maps/helpers.js'
import { pinch, wheelOut, scale, frame } from './fixtures/pinch.js'
test.use({ hasTouch: true, viewport: { width: 704, height: 932 } })
test.beforeEach(async ({ page }) => { page.on('pageerror', error => { throw error }) })

test('story graph pinches in and out without moving nodes and retains wheel zoom', async ({ page }) => {
  const writes = []
  page.on('request', request => { if (request.method() !== 'GET' && /\/(chapter|scene|block)-graph/.test(request.url())) writes.push(request.url()) })
  await sessionLayout(page, { url: '/sessions/test' })
  const host = page.locator('.nested-graph-canvas'), world = host.locator('.nested-graph-world')
  await expect(host).toBeVisible()
  const before = await scale(world)
  const nodes = await host.locator('.nested-graph-node').evaluateAll(nodes => nodes.map(node => [node.style.left, node.style.top]))
  await pinch(page, host)
  expect(await scale(world)).toBeGreaterThan(before)
  const enlarged = await scale(world)
  await pinch(page, host, .65)
  expect(await scale(world)).toBeLessThan(enlarged)
  const reduced = await scale(world)
  await wheelOut(page, host)
  expect(await scale(world)).toBeLessThan(reduced)
  expect(await host.locator('.nested-graph-node').evaluateAll(nodes => nodes.map(node => [node.style.left, node.style.top]))).toEqual(nodes)
  expect(writes).toEqual([])
})

test('world pinch in point placement mode does not add or move route points', async ({ page }) => {
  const api = await setup(page)
  api.maps.push({ id: 'map-1', name: 'Мир', imageId: 1, imageUrl: '/test-global-world.svg', current: true, revision: 1,
    routes: [{ id: 'route-1', name: 'Путь', color: '#8855cc', playerIds: [], points: [{ id: 'a', x: .5, y: .5, name: 'Башня', note: '', chapterId: null }] }] })
  await open(page)
  await expect(page.locator('.global-map-image')).toHaveJSProperty('complete', true)
  await page.getByRole('navigation', { name: 'Боковые вкладки сессии', exact: true }).getByRole('button', { name: 'Маршруты', exact: true }).click()
  await page.getByRole('button', { name: 'Открыть маршрут Путь', exact: true }).click()
  await page.getByRole('button', { name: 'Добавить точку на карту', exact: true }).click()
  const host = page.locator('.global-map-canvas'), world = page.locator('.global-map-world')
  const marker = page.locator('[data-point-id="a"]').first(), box = await marker.boundingBox()
  const initial = JSON.stringify(api.maps[0].routes)
  const before = await scale(world)
  await pinch(page, host, 1.7, { x: box.x + box.width / 2 + 35, y: box.y + box.height / 2 })
  expect(await scale(world)).toBeGreaterThan(before)
  const enlarged = await scale(world)
  await pinch(page, host, .65)
  expect(await scale(world)).toBeLessThan(enlarged)
  const reduced = await scale(world); await wheelOut(page, host)
  expect(await scale(world)).toBeLessThan(reduced)
  expect(JSON.stringify(api.maps[0].routes)).toBe(initial)
  expect(api.writes).toEqual([])
})

async function readyMap(page) {
  await page.goto('/tests/maps/fixtures/maps.html?mode=editor')
  await expect(page.locator('.map-canvas-surface canvas')).toBeVisible()
  await expect(page.getByText('Подготавливаем карту…')).toHaveCount(0)
  const collapse = page.getByRole('button', { name: 'Свернуть панель карты', exact: true })
  if (await collapse.isVisible()) await collapse.click()
  await frame(page)
}
const view = page => page.locator('.map-canvas').evaluate(node => node.__vueParentComponent.exposed.getView())
test('tactical map pinches without rotating, placing or saving geometry', async ({ page }) => {
  await readyMap(page)
  const host = page.locator('.map-canvas-surface'), before = await view(page)
  await pinch(page, host)
  const enlarged = await view(page)
  expect(enlarged.cellPixels).toBeGreaterThan(before.cellPixels)
  expect(enlarged.tilt).toBe(before.tilt); expect(enlarged.azimuth).toBe(before.azimuth)
  await pinch(page, host, .65)
  const reduced = await view(page); expect(reduced.cellPixels).toBeLessThan(enlarged.cellPixels)
  await wheelOut(page, host)
  expect((await view(page)).cellPixels).toBeLessThan(reduced.cellPixels)
  expect(await page.evaluate(() => window.requests.filter(request => request.url === '/api/maps/test-map' && request.data?.patches?.some(patch => ['tiles','objects','lights','decals'].some(key => patch.path?.includes(key)))))).toEqual([])
})

test('model parameter preview pinches without rotation or editing ports', async ({ page }) => {
  await readyMap(page)
  await page.getByRole('button', { name: 'Справочник тайлов', exact: true }).click()
  const catalogue = page.locator('.map-reference-catalogue')
  await catalogue.getByRole('button', { name: 'Стены', exact: true }).click()
  await catalogue.getByRole('button', { name: 'Стена 1', exact: true }).click()
  const preview = page.locator('.model-preview'), host = page.locator('.model-preview-host')
  await expect(preview).toHaveAttribute('data-preview-zoom', '1')
  await expect(preview.locator('[data-preview-port]')).toHaveCount(8)
  const ports = await preview.getByRole('button', { name: /^Стык:/ }).evaluateAll(nodes => nodes.map(node => node.getAttribute('aria-pressed')))
  const yaw = await preview.getAttribute('data-preview-yaw')
  await pinch(page, host)
  expect(Number(await preview.getAttribute('data-preview-zoom'))).toBeGreaterThan(1)
  await expect(preview).toHaveAttribute('data-preview-yaw', yaw)
  const enlarged = Number(await preview.getAttribute('data-preview-zoom'))
  await pinch(page, host, .65)
  expect(Number(await preview.getAttribute('data-preview-zoom'))).toBeLessThan(enlarged)
  const reduced = Number(await preview.getAttribute('data-preview-zoom')); await wheelOut(page, host)
  expect(Number(await preview.getAttribute('data-preview-zoom'))).toBeLessThan(reduced)
  expect(await preview.getByRole('button', { name: /^Стык:/ }).evaluateAll(nodes => nodes.map(node => node.getAttribute('aria-pressed')))).toEqual(ports)
  expect(await page.evaluate(() => window.lastModelSaved || null)).toBe(null)
})
