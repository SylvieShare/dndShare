import {test,expect} from '@playwright/test'

async function inspectMaterial(page,scope,{name,priceLabel},info,shot) {
 await expect(scope.locator('.spell-material-requirement')).toHaveCount(0)
 await expect(page.locator('.spell-material-requirement')).toHaveCount(0)
 await scope.locator('.spell-component-trigger').click()
 const dialog=page.getByRole('dialog',{name:'Компоненты заклинания',exact:true})
 await expect(dialog).toBeVisible()
 await expect(dialog.locator('.spell-material-name')).toContainText(name)
 if(priceLabel) {
  await expect(dialog.locator('.spell-material-price')).toHaveText(priceLabel)
  await expect(dialog.locator('.spell-material-requirement')).toHaveClass(/requirement--priced/)
 } else {
  await expect(dialog.locator('.spell-material-price')).toHaveCount(0)
  await expect(dialog.locator('.spell-material-requirement')).not.toHaveClass(/requirement--priced/)
 }
 const box=await dialog.boundingBox()
 expect(box.x).toBeGreaterThanOrEqual(0)
 expect(box.x+box.width).toBeLessThanOrEqual(page.viewportSize().width+1)
 await expect(page.getByRole('button',{name:'Открыть описание',exact:true})).toHaveCount(0)
 if(shot)await info.attach(shot,{body:await dialog.screenshot(),contentType:'image/png'})
 await page.keyboard.press('Escape')
 await expect(dialog).toHaveCount(0)
 await expect(page.locator('.spell-material-requirement')).toHaveCount(0)
}

