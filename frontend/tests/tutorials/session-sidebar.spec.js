import { expect,test } from '@playwright/test'

for(const width of [390,834,1440])test(`one persistent session sidebar at ${width}`,async({page},info)=>{
  page.on('pageerror',error=>{throw error})
  await page.setViewportSize({width,height:900})
  await page.goto('/tests/tutorials/fixtures/session-sidebar.html')
  const sidebar=page.locator('aside.map-sidebar'),nav=page.getByRole('navigation',{name:'Боковые вкладки сессии'})
  await expect(sidebar).toHaveCount(1)
  const original=await sidebar.elementHandle()
  const players=page.locator('[data-tutorial="session-players"]')
  if((await sidebar.getAttribute('class')).includes('map-sidebar--collapsed'))await nav.getByRole('button',{name:'Игроки',exact:true}).click()
  await expect(players.locator('.health-readout')).toHaveText('18/24')
  await expect(players.locator('.health-temporary')).toHaveText('+5')
  await expect(players.locator('.heading-armor-value')).toHaveText('12')
  await expect(players.locator('.heading-metric')).toHaveText(['16','18'])
  const status=players.getByRole('button',{name:'Благословение',exact:true})
  await expect(status).toContainText('1 минута')
  await expect(status.locator('.item-icon')).toHaveCSS('width','40px')
  await expect(sidebar).toHaveCSS('border-top-width','1px')
  await expect(nav).not.toHaveCSS('box-shadow','none')
  await expect(sidebar).toHaveCSS('opacity','1')
  await info.attach('session-players',{body:await sidebar.screenshot(),contentType:'image/png'})
  await page.evaluate(()=>{window.sidebarState.view='maps'})
  await nav.getByRole('button',{name:'Плитки',exact:true}).click()
  await page.getByRole('textbox',{name:'Черновик карты'}).fill('Сохраняем локальный ввод')
  await expect(players).not.toBeVisible()
  await page.evaluate(()=>{window.sidebarState.view='globalMaps'})
  await expect(nav.getByRole('button')).toHaveCount(3)
  await nav.getByRole('button',{name:'Маршруты',exact:true}).click()
  await expect(page.getByTestId('world-panel')).toHaveText('routes')
  await page.evaluate(()=>{window.sidebarState.view='journal'})
  await expect(nav.getByRole('button')).toHaveCount(1)
  await expect(players).toBeVisible()
  await page.evaluate(()=>{window.sidebarState.view='maps'})
  await nav.getByRole('button',{name:'Плитки',exact:true}).click()
  await expect(page.getByRole('textbox',{name:'Черновик карты'})).toHaveValue('Сохраняем локальный ввод')
  expect(await original.evaluate(node=>node.isConnected)).toBe(true)
  await expect(sidebar).toHaveCount(1)
  expect(await page.evaluate(()=>document.documentElement.scrollWidth)).toBeLessThanOrEqual(width)
})
