test.describe('touch selection lane',()=>{
  test.use({hasTouch:true,isMobile:true})
  test('checkbox taps select immediately and vertical gestures scroll both rosters',async({page})=>{
    const api=await rosterSelectionFixture(page,834)
    for(let i=2;i<16;i++){
      api.participants.push({...structuredClone(api.participants[0]),charId:i+1,charUuid:`extra-${i}`,data:{values:{...structuredClone(api.participants[0].data.values),name:`Игрок ${i}`}}})
      api.encounter().combatants.push({uid:`p-${i+1}`,type:'player',charId:i+1,charUuid:`extra-${i}`,position:'reserve'})
    }
    const wolf=api.encounter().combatants.find(c=>c.uid==='wolf')
    for(let i=1;i<12;i++)api.encounter().combatants.push({...structuredClone(wolf),uid:`wolf-${i}`,override:{...wolf.override,name:`Волк ${i}`}})
    await page.reload()
    const sidebar=page.locator('aside.map-sidebar'),nav=sidebar.getByRole('navigation'),touch=await page.context().newCDPSession(page)
    for(const tab of ['Игроки','Запас']){
      await nav.getByRole('button',{name:tab,exact:true}).click()
      const list=sidebar.locator('.session-roster-list:visible'),check=list.getByRole('checkbox').first()
      const tile=check.locator('xpath=../..')
      await tile.scrollIntoViewIfNeeded()
      const tileBox=await tile.boundingBox(),box=await check.boundingBox()
      const start={x:box.x+box.width/2,y:tileBox.y+tileBox.height-5}
      await page.touchscreen.tap(start.x,start.y)
      await expect(check).toBeChecked()
      await expect(page.getByRole('menu')).toHaveCount(0)
      await touch.send('Input.dispatchTouchEvent',{type:'touchStart',touchPoints:[start]})
      for(let i=1;i<=6;i++)await touch.send('Input.dispatchTouchEvent',{type:'touchMove',touchPoints:[{x:start.x,y:start.y-i*22}]})
      await touch.send('Input.dispatchTouchEvent',{type:'touchEnd',touchPoints:[]})
      await expect.poll(()=>list.evaluate(n=>n.scrollTop)).toBeGreaterThan(20)
      await expect(page.locator('.sortable-ghost')).toHaveCount(0)
      await expect(check).toBeChecked()
    }
    expect(api.writes).toHaveLength(0);expect(api.errors).toEqual([]);expect(api.warnings).toEqual([])
    await touch.detach()
  })
})
