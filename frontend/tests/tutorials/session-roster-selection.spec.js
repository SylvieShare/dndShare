import { expect, test } from '@playwright/test'
import { rosterSelectionFixture as fixture } from './fixtures/session-roster.js'


for(const width of [390,834,1440])test(`shared roster selection, scoped damage, experience and prepared combat at ${width}`,async({page},info)=>{
  const api=await fixture(page,width)
  const nav=page.getByRole('navigation',{name:'Боковые вкладки сессии'}),sidebar=page.locator('aside.map-sidebar')
  await expect(nav.getByRole('button').nth(1)).toHaveAccessibleName('Запас',{timeout:15000})
  await expect(nav.getByRole('separator')).toHaveCount(0)
  await nav.getByRole('button',{name:'Запас',exact:true}).click()
  const reserve=sidebar.getByRole('region',{name:'Запас существ',exact:true})
  await expect(reserve.locator('.heading-armor-value')).toHaveText('14')
  await expect(reserve.locator('.health-readout')).toHaveText('15/20')
  await expect(reserve.getByRole('button',{name:'Благословение',exact:true})).toContainText('2 раунда')
  await expect(reserve.locator('.item-icon').first()).toHaveCSS('width','40px')
  await reserve.getByRole('button',{name:'Выбрать',exact:true}).click()
  const wolf=reserve.getByRole('checkbox',{name:'Выбрать: Волк',exact:true})
  await expect(wolf).not.toBeChecked()
  await expect(reserve.locator('input[type="checkbox"]')).toHaveCount(0)
  await wolf.click()
  await expect(wolf).toBeChecked()
  await info.attach(`reserve-selection-${width}`,{body:await sidebar.screenshot({animations:'disabled'}),contentType:'image/png'})
  await nav.getByRole('button',{name:'Игроки',exact:true}).click()
  const players=sidebar.locator('[data-tutorial="session-players"]')
  await players.getByRole('button',{name:'Выбрать',exact:true}).click()
  const first=players.getByRole('checkbox',{name:'Выбрать: Лира',exact:true}),second=players.getByRole('checkbox',{name:'Выбрать: Тиф',exact:true})
  await expect(first).not.toBeChecked()
  await first.click()
  await expect(first).toBeChecked()
  await expect(second).not.toBeChecked()
  await info.attach(`player-selection-${width}`,{body:await sidebar.screenshot({animations:'disabled'}),contentType:'image/png'})
  const shadows=await players.locator('.session-roster-tile').evaluateAll(nodes=>nodes.map(n=>getComputedStyle(n).boxShadow))
  expect(shadows[0]).not.toBe(shadows[1])
  await expect(page.getByRole('menu')).toHaveCount(0)
  await expect(players.getByRole('button',{name:'Переместить в бой',exact:true})).toHaveCount(0)
  await page.locator('.chapter-toolbar').getByRole('button',{name:'Материалы',exact:true}).click()
  await expect(first).toBeChecked()
  await players.getByRole('button',{name:'Добавить опыт',exact:true}).click()
  const xp=page.getByRole('dialog',{name:'Добавить опыт',exact:true})
  await xp.getByRole('spinbutton').fill('100')
  await xp.getByRole('button',{name:'Добавить опыт',exact:true}).click()
  await expect(xp).toHaveCount(0)
  expect(api.participants.map(p=>p.data.values.lvl.exp)).toEqual([800,700])
  expect(api.writes).toHaveLength(1)
  await players.getByRole('button',{name:'Нанести урон',exact:true}).click()
  const damage=page.getByRole('dialog',{name:'Нанести урон',exact:true})
  await damage.getByRole('spinbutton').fill('5')
  await damage.getByRole('button',{name:'Нанести урон',exact:true}).click()
  await expect(damage).toHaveCount(0)
  expect(api.impacts).toHaveLength(1)
  expect(api.impacts[0].targets).toEqual([{target:{kind:'character',charUuid:'player-0'}}])
  expect(api.participants.map(p=>p.data.values.hp.current)).toEqual([15,18])
  expect(api.encounter().combatants.find(row=>row.uid==='wolf').hpCurrent).toBe(15)
  await page.getByRole('button',{name:/Открыть бой/}).click()
  await expect(players.getByRole('button',{name:'Переместить в бой',exact:true})).toBeVisible()
  await players.getByRole('button',{name:'Переместить в бой',exact:true}).click()
  await players.getByRole('button',{name:'Готово',exact:true}).click()
  await expect(players.getByRole('checkbox')).toHaveCount(0)
  await expect(page.locator('[data-encounter-section="combat"][data-encounter-uid="p-1"]')).toBeVisible()
  expect(api.encounter().active).toBe(false)
  await nav.getByRole('button',{name:'Запас',exact:true}).click()
  await expect(wolf).toBeChecked()
  await reserve.getByRole('button',{name:'Переместить в бой',exact:true}).click()
  await expect(page.locator('[data-encounter-section="combat"][data-encounter-uid="wolf"]')).toBeVisible()
  await expect(reserve.getByText('Запас пуст',{exact:true})).toBeVisible()
  expect(api.encounter().active).toBe(false)
  await sidebar.getByRole('button',{name:'Свернуть боковую панель',exact:true}).click()
  await page.getByRole('button',{name:'Начать бой',exact:true}).click()
  await expect.poll(()=>api.encounter().active).toBe(true)
  expect(api.encounter().combatants.filter(row=>row.position==='combat').map(row=>row.uid).sort()).toEqual(['p-1','wolf'])
  await info.attach(`roster-${width}`,{body:await page.screenshot({animations:'disabled'}),contentType:'image/png'})
  await page.locator('.chapter-toolbar').getByRole('button',{name:'Мир',exact:true}).click()
  await expect(nav.getByRole('separator',{name:'Инструменты раздела',exact:true})).toHaveCount(1)
  const add=await nav.getByRole('button',{name:'Добавить вкладку',exact:true}).boundingBox(),divider=await nav.getByRole('separator',{name:'Инструменты раздела',exact:true}).boundingBox()
  expect(divider.y).toBeGreaterThanOrEqual(add.y+add.height)
  expect(api.errors).toEqual([])
  expect(api.warnings).toEqual([])
})
