import { expect, test } from '@playwright/test'
import { rosterSelectionFixture } from './fixtures/session-roster.js'

for(const width of [390,834,1440])test(`roster header, edge scrollbar and brush selection at ${width}`,async({page},info)=>{
  const api=await rosterSelectionFixture(page,width)
  for(let i=2;i<16;i++){
    api.participants.push({...structuredClone(api.participants[0]),charId:i+1,charUuid:`extra-player-${i}`,data:{values:{...structuredClone(api.participants[0].data.values),name:`Игрок ${i+1}`}}})
    api.encounter().combatants.push({uid:`p-${i+1}`,type:'player',charId:i+1,charUuid:`extra-player-${i}`,position:'reserve'})
  }
  const wolf=api.encounter().combatants.find(row=>row.uid==='wolf')
  for(let i=1;i<16;i++)api.encounter().combatants.push({...structuredClone(wolf),uid:`wolf-${i}`,override:{...wolf.override,name:`Волк ${i+1}`}})
  await page.reload()
  const sidebar=page.locator('aside.map-sidebar'),nav=sidebar.getByRole('navigation'),header=sidebar.locator('.map-sidebar-header'),counter=header.getByRole('status')
  if((await sidebar.getAttribute('class')).includes('map-sidebar--collapsed'))await nav.getByRole('button',{name:'Игроки',exact:true}).click()
  await expect(header.locator('.roster-selection')).toBeVisible()
  await expect(header).toHaveCSS('border-bottom-width','0px')
  expect(await header.evaluate(n=>getComputedStyle(n).backgroundColor)).not.toBe(await sidebar.locator('.map-sidebar-panel').evaluate(n=>getComputedStyle(n).backgroundColor))
  for(const tab of ['Игроки','Запас']){
    if(tab==='Запас')await nav.getByRole('button',{name:tab,exact:true}).click()
    const hovered=sidebar.locator('.session-roster-list:visible .session-roster-tile').nth(1)
    await hovered.hover()
    await expect(hovered).toHaveCSS('background-color','rgba(0, 0, 0, 0)')
    await expect.poll(()=>hovered.evaluate(n=>getComputedStyle(n,'::before').opacity)).toBe('0.11')
    expect(await hovered.evaluate(n=>getComputedStyle(n,'::before').clipPath)).not.toBe('none')
    await info.attach(`hover-${tab}-${width}`,{body:await sidebar.screenshot({animations:'disabled'}),contentType:'image/png'})
    await header.hover()
    await expect.poll(()=>hovered.evaluate(n=>getComputedStyle(n,'::before').opacity)).toBe('0')
  }
  await nav.getByRole('button',{name:'Игроки',exact:true}).click()
  let count=0
  for(const tab of ['Игроки','Запас']){
    if(tab==='Запас')await nav.getByRole('button',{name:tab,exact:true}).click()
    const list=sidebar.locator('.session-roster-list:visible')
    await expect(list).toHaveAttribute('data-scrollable','true')
    const geometry=await list.evaluate(n=>({right:n.getBoundingClientRect().right,panelRight:n.closest('.map-sidebar-panel').getBoundingClientRect().right,border:parseFloat(getComputedStyle(n.closest('.map-sidebar-panel')).borderRightWidth),gutter:getComputedStyle(n).scrollbarGutter,gap:getComputedStyle(n).gap}))
    expect(geometry.panelRight-geometry.right).toBeCloseTo(geometry.border,0)
    expect(geometry.gutter).toBe('auto');expect(geometry.gap).toBe('0px')
    await expect(list).toHaveCSS('padding-left','0px')
    await expect(list).toHaveCSS('padding-right','0px')
    const bounds=await list.evaluate(n=>({left:n.getBoundingClientRect().left,panelLeft:n.closest('.map-sidebar-panel').getBoundingClientRect().left,border:parseFloat(getComputedStyle(n.closest('.map-sidebar-panel')).borderLeftWidth)}))
    expect(bounds.left-bounds.panelLeft).toBeCloseTo(bounds.border,0)
    const row=list.locator('.session-roster-tile').first(),tile=row,before=await row.boundingBox(),checkbox=row.getByRole('checkbox')
    await checkbox.click()
    await expect(checkbox).toBeChecked()
    await expect(counter).toHaveText(`Выбрано: ${++count}`)
    await expect(tile).toHaveCSS('border-radius','0px')
    await expect.poll(()=>tile.evaluate(n=>getComputedStyle(n,'::before').opacity)).toBe('0.13')
    expect((await row.boundingBox()).height).toBeCloseTo(before.height,1)
    await expect(list.locator('.workspace-row-divider--rough')).toHaveCount(15)
    const paths=await list.locator('.workspace-row-divider--rough path').evaluateAll(nodes=>nodes.slice(0,5).map(n=>n.getAttribute('d')))
    expect(new Set(paths).size).toBe(5)
    const seam=list.locator('.workspace-row-divider--rough').first()
    await expect(seam).toHaveCSS('mask-image','none')
    const line=await seam.boundingBox(),next=await list.locator('.session-roster-tile').nth(1).boundingBox(),filled=await tile.boundingBox()
    expect(line.y+line.height/2).toBeCloseTo(next.y,1)
    expect(filled.y+filled.height).toBeCloseTo(next.y,1)
    expect(line.x).toBeCloseTo(filled.x,1)
    expect(line.width).toBeCloseTo(filled.width,1)
    await expect.poll(()=>tile.evaluate(n=>getComputedStyle(n,'::after').opacity)).toBe('0.34')
    const nextRow=list.locator('.session-roster-tile').nth(1)
    await nextRow.getByRole('checkbox').click()
    await expect(nextRow.getByRole('checkbox')).toBeChecked()
    await expect(counter).toHaveText(`Выбрано: ${++count}`)
    expect(await tile.evaluate(n=>getComputedStyle(n,'::before').clipPath)).not.toBe(await nextRow.evaluate(n=>getComputedStyle(n,'::before').clipPath))
    const top=(await header.boundingBox()).y
    await list.evaluate(n=>n.scrollTop=n.scrollHeight)
    expect((await header.boundingBox()).y).toBe(top)
    await expect(counter).toHaveText(`Выбрано: ${count}`)
    await list.evaluate(n=>n.scrollTop=0)
    await info.attach(`roster-${tab}-${width}`,{body:await sidebar.screenshot({animations:'disabled'}),contentType:'image/png'})
  }
  await header.getByRole('button',{name:'Сбросить выбор',exact:true}).click()
  await expect(sidebar.locator('[role=checkbox][aria-checked=true]')).toHaveCount(0)
  await page.setViewportSize({width,height:2600})
  await expect(sidebar.locator('.session-roster-list:visible')).not.toHaveAttribute('data-scrollable','true')
  expect(api.errors).toEqual([]);expect(api.warnings).toEqual([])
})
