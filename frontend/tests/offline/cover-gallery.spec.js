import { test, expect } from '@playwright/test'

for (const width of [390, 834, 1440]) test(`cover controls and the displayed-photo mark follow native updates at ${width}`, async ({ page }, testInfo) => {
  const errors = []; page.on('pageerror', error => errors.push(error.message))
  await page.setViewportSize({ width, height: 900 })
  await page.goto('/tests/offline/fixtures/cover-gallery.html')
  const gallery = page.getByLabel('Галерея персонажа', { exact: true })
  const controls = gallery.getByRole('button', { name: 'Настройка внешнего экрана' })
  const title = await gallery.getByText('Галерея', { exact: true }).boundingBox()
  const button = await controls.boundingBox()
  expect(button.x).toBeGreaterThan(title.x + title.width)
  expect(Math.abs(button.y + button.height / 2 - title.y - title.height / 2)).toBeLessThan(4)
  await controls.click()
  const automatic = page.getByRole('switch', { name: 'Автоматический показ' })
  await expect(automatic).toHaveAttribute('aria-checked', 'false')
  await automatic.click()
  await expect(automatic).toHaveAttribute('aria-checked', 'true')
  await expect(gallery.getByRole('button', { name: 'Фотография 1', exact: true })).toHaveClass(/photo-thumb--displayed/)
  await expect(gallery.getByText('На экране', { exact: true })).toHaveCount(1)
  await page.keyboard.press('Escape')
  await page.evaluate(() => window.coverUpdate({ photoUid: 'landscape', displayWidth: 1200, displayHeight: 600 }))
  await expect(gallery.getByRole('button', { name: 'Фотография 2', exact: true })).toHaveClass(/photo-thumb--displayed/)
  await expect(gallery.getByRole('button', { name: 'Фотография 1', exact: true })).not.toHaveClass(/photo-thumb--displayed/)
  await controls.click()
  await automatic.click()
  await expect(automatic).toHaveAttribute('aria-checked', 'false')
  await page.keyboard.press('Escape')
  await expect(page.getByRole('menu')).toHaveCount(0)
  await expect(page.locator('.base-popover')).toHaveCount(0)
  await expect(gallery.getByRole('button', { name: 'Фотография 2', exact: true })).toHaveClass(/photo-thumb--displayed/)
  await gallery.screenshot({ path: testInfo.outputPath('cover-gallery.png') })
  expect(errors).toEqual([])
  expect(await page.evaluate(() => window.coverCalls.map(call => call[0]))).toEqual(['start', 'pause'])
})

test('deleting the displayed photograph updates an automatic playlist and stopping clears the mark', async ({ page }) => {
  await page.goto('/tests/offline/fixtures/cover-gallery.html')
  await page.getByRole('button', { name: 'Настройка внешнего экрана' }).click()
  await page.getByRole('switch', { name: 'Автоматический показ' }).click()
  await page.keyboard.press('Escape')
  await page.getByRole('button', { name: 'Фотография 1', exact: true }).click()
  await page.getByRole('menuitem', { name: 'Удалить', exact: true }).click()
  await page.getByRole('dialog').getByRole('button', { name: 'Удалить', exact: true }).click()
  await expect(page.locator('.photo-thumb--displayed')).toHaveCount(1)
  await expect(page.locator('.photo-thumb--displayed img')).toHaveAttribute('alt', 'Пейзаж')
  expect(await page.evaluate(() => window.coverCalls.at(-1)[0])).toBe('update')
  await page.getByRole('button', { name: 'Настройка внешнего экрана' }).click()
  await page.getByRole('menuitem', { name: 'Убрать с внешнего экрана' }).click()
  await expect(page.locator('.photo-thumb--displayed')).toHaveCount(0)
})

test('web omits external-screen controls and unsupported devices explain the limitation', async ({ page }) => {
  await page.goto('/tests/offline/fixtures/cover-gallery.html?mode=web')
  await expect(page.getByRole('button', { name: 'Добавить', exact: true })).toBeVisible()
  await expect(page.getByRole('button', { name: 'Настройка внешнего экрана' })).toHaveCount(0)
  await page.goto('/tests/offline/fixtures/cover-gallery.html?mode=unavailable')
  await page.getByRole('button', { name: 'Настройка внешнего экрана' }).click()
  await expect(page.getByRole('switch', { name: 'Автоматический показ' })).toBeDisabled()
  await expect(page.getByText('Прошивка не предоставляет доступ к внешнему экрану')).toBeVisible()
})
