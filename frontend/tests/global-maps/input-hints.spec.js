import { test, expect } from '@playwright/test'
import { setup, open } from './helpers'

test.use({ hasTouch: true })

for (const width of [704, 1440]) test(`touch legends preserve actions and react to a mouse at ${width}`, async ({ page, context }, info) => {
  await page.setViewportSize({ width, height: 932 })
  const state = await setup(page)
  await page.route('**/api/handbook/sync?**', route => route.fulfill({ json: { protocol: 1, entries: [], hasMore: false, cursor: 'empty', visibleIds: [], metadata: { types: [], suggests: {}, suggestTypes: [], books: [] } } }))
  state.maps.push({ id: 'world', name: 'Мир', imageId: 1, imageUrl: '/test-global-world.svg', current: true, revision: 1,
    routes: [{ id: 'route', name: 'Путь', color: '#b397df', playerIds: [], points: [{ id: 'a', x: .3, y: .4, name: 'Начало' }] }] })
  await open(page)
  await expect(page.locator('.global-map-canvas img')).toBeVisible()
  await expect(page.locator('.global-map-controls-hint')).toHaveCount(0)
  await page.locator('button[data-source-id="a"]').click()
  await page.getByRole('complementary', { name: 'Настройки точки', exact: true }).getByRole('button', { name: 'Открыть маршрут Путь', exact: true }).click()
  const routeFocus = page.getByRole('complementary', { name: 'Настройки маршрута', exact: true })
  await routeFocus.getByRole('button', { name: 'Добавить точку на карту', exact: true }).click()
  const hint = page.locator('.global-map-controls-hint')
  await expect(hint.getByRole('button', { name: 'Готово', exact: true })).toBeVisible()
  await expect(hint.getByLabel('Команды управления миром', { exact: true })).toHaveCount(0)
  await expect(hint.getByRole('button', { name: 'Управление миром', exact: true })).toHaveCount(0)
  await hint.getByRole('button', { name: 'Готово', exact: true }).click()
  await expect(routeFocus).toBeVisible()
  await expect(hint).toHaveCount(0)
  await page.getByRole('button', { name: 'Сюжет', exact: true }).click()
  await expect(page.locator('.session-graph-canvas')).toBeVisible()
  await expect(page.locator('.canvas-hotkeys')).toHaveCount(0)
  await info.attach('touch-story', { body: await page.screenshot(), contentType: 'image/png' })
  const cdp = await context.newCDPSession(page)
  await cdp.send('Emulation.setTouchEmulationEnabled', { enabled: false })
  const commands = page.getByRole('list', { name: 'Команды управления сюжетом', exact: true })
  await expect(commands).toBeVisible()
  await commands.focus()
  await page.keyboard.press('Enter')
  const toggle = page.getByRole('button', { name: 'Управление сюжетом', exact: true })
  await expect(toggle).toBeFocused()
  await page.keyboard.press('Enter')
  await expect(commands).toBeFocused()
  await info.attach('mouse-story', { body: await page.screenshot(), contentType: 'image/png' })
  await cdp.send('Emulation.setTouchEmulationEnabled', { enabled: true, maxTouchPoints: 5 })
  await expect(page.locator('.canvas-hotkeys')).toHaveCount(0)
  await cdp.detach()
  expect(state.writes).toHaveLength(0)
})
