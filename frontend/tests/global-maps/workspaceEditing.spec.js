import { test, expect } from '@playwright/test'
import { open, openRoute, setup } from './helpers'
import { openWorldTab } from './helpers'

async function seeded(page, mobile = false) {
  await page.setViewportSize(mobile ? { width: 430, height: 932 } : { width: 1600, height: 1000 })
  const state = await setup(page)
  state.maps.push({ id: 'world', name: 'Мир', imageId: 1, imageUrl: '/test-global-world.svg', current: true, revision: 1, routes: [{ id: 'route', name: 'Путь', color: '#b397df', playerIds: [], points: [
    { id: 'a', x: .2, y: .4, name: 'Начало' }, { id: 'b', x: .5, y: .4, name: 'Привал' }, { id: 'c', x: .8, y: .4, name: 'Конец' },
  ] }] })
  await open(page)
  await expect(page.getByText('Загружаем изображение…', { exact: true })).toHaveCount(0)
  return state
}

for (const mobile of [false, true]) test(`map tiles rename in place and delete individually ${mobile ? 'mobile' : 'desktop'}`, async ({ page }) => {
  const state = await setup(page)
  await page.setViewportSize(mobile ? { width: 430, height: 932 } : { width: 1600, height: 1000 })
  state.maps.push(...['Мир', 'Регион'].map((name, index) => ({ id: `map-${index}`, name, imageId: 1, imageUrl: '/test-global-world.svg', current: index === 0, revision: 1, routes: [] })))
  await open(page)
  await openWorldTab(page, 'Карты мира')
  await expect(page.getByRole('textbox', { name: 'Название карты мира', exact: true })).toHaveCount(0)
  await page.getByRole('button', { name: 'Переименовать карту Регион', exact: true }).click()
  await page.getByRole('textbox', { name: 'Название карты Регион', exact: true }).fill('Атлас')
  await page.keyboard.press('Enter')
  await expect.poll(() => state.maps[1].name).toBe('Атлас')
  await expect(page.locator('.global-map-thumbnail--selected')).toContainText('Мир')
  await page.getByRole('button', { name: 'Переименовать карту Мир', exact: true }).click()
  await page.getByRole('textbox', { name: 'Название карты Мир', exact: true }).fill('Отмена')
  await page.keyboard.press('Escape')
  expect(state.maps[0].name).toBe('Мир')
  await page.getByRole('button', { name: 'Удалить карту Атлас', exact: true }).click()
  await page.getByRole('dialog').getByRole('button', { name: 'Удалить', exact: true }).click()
  await expect.poll(() => state.maps.length).toBe(1)
  expect(state.maps[0].name).toBe('Мир')
})

for (const mobile of [false, true]) test(`route focus owns ordering and point focus links back ${mobile ? 'mobile' : 'desktop'}`, async ({ page }) => {
  const state = await seeded(page, mobile)
  await page.locator('[data-source-id="a"]').click()
  const pointFocus = page.getByRole('complementary', { name: 'Настройки точки', exact: true })
  await expect(pointFocus.getByRole('button', { name: 'Передвинуть точку раньше', exact: true })).toHaveCount(0)
  await pointFocus.getByRole('button', { name: 'Открыть маршрут Путь', exact: true }).click()
  const routeFocus = page.getByRole('complementary', { name: 'Настройки маршрута', exact: true })
  await expect(routeFocus).toBeVisible()
  await expect(pointFocus).toHaveCount(0)
  const first = page.locator('.global-route-point-handle').first()
  if (mobile) {
    await first.focus(); await page.keyboard.press('ArrowDown'); await page.keyboard.press('ArrowDown')
  } else {
    await first.scrollIntoViewIfNeeded()
    const from = await first.boundingBox(), target = await page.locator('.global-route-point-row').last().boundingBox()
    await page.mouse.move(from.x + from.width / 2, from.y + from.height / 2)
    await page.mouse.down()
    await page.mouse.move(target.x + 20, target.y + target.height - 2, { steps: 10 })
    await page.mouse.up()
  }
  await expect.poll(() => state.maps[0].routes[0].points.map(point => point.id)).toEqual(['b', 'c', 'a'])
  await expect(routeFocus.getByRole('listitem')).toHaveCount(3)
  await routeFocus.getByRole('button', { name: '3. Начало', exact: true }).click()
  await expect(pointFocus.getByRole('heading', { name: 'Начало', exact: true })).toBeVisible()
  await page.reload()
  await openRoute(page)
  await expect(page.locator('.global-route-point-open').first()).toContainText('Привал')
})

test('adding a stop leaves previous leg paths unchanged and starts a new dashed path at its source', async ({ page }) => {
  const state = await seeded(page)
  const before = await page.locator('.global-map-route-line').evaluateAll(paths => paths.map(path => path.getAttribute('d')))
  const image = await page.locator('.global-map-image').boundingBox()
  await page.mouse.move(image.x + image.width * .7, image.y + image.height * .75)
  await page.keyboard.down('Meta')
  const preview = await page.locator('.global-map-route-preview path').first().getAttribute('d')
  await page.mouse.click(image.x + image.width * .7, image.y + image.height * .75)
  await page.keyboard.up('Meta')
  await expect.poll(() => state.maps[0].routes[0].points.length).toBe(4)
  const after = await page.locator('.global-map-route-line').evaluateAll(paths => paths.map(path => path.getAttribute('d')))
  expect(after.slice(0, 2)).toEqual(before)
  expect(after[2]).toBe(preview)
  expect(after[2]).toMatch(/^M960,320 C/)
})

for (const mobile of [false, true]) test(`toolbar tools hover, touch and keyboard ${mobile ? 'mobile' : 'desktop'}`, async ({ page }) => {
  await seeded(page, mobile)
  const trigger = page.getByRole('button', { name: 'Инструменты', exact: true })
  const menu = page.getByRole('menu', { name: 'Инструменты сессии', exact: true })
  await expect(page.locator('.workspace-tools-rail')).toHaveCount(0)
  if (mobile) await trigger.dispatchEvent('click')
  else await trigger.hover()
  await expect(menu).toBeVisible()
  await expect(menu.getByRole('menuitem')).toHaveCount(4)
  await menu.getByRole('menuitem', { name: 'Кубики', exact: true }).click()
  await expect(menu).toHaveCount(0)
  await expect(page.locator('.dice-panel')).toBeVisible()
  await page.keyboard.press('Escape')
  await expect(page.locator('.dice-panel')).toHaveCount(0)
  await trigger.focus()
  await page.keyboard.press('ArrowDown')
  await expect(menu.getByRole('menuitem').first()).toBeFocused()
  await page.keyboard.press('ArrowDown')
  await expect(menu.getByRole('menuitem').nth(1)).toBeFocused()
  await page.keyboard.press('Escape')
  await expect(menu).toHaveCount(0)
  await page.locator('.global-map-canvas').focus()
  await page.keyboard.press('Shift+D')
  await expect(page.locator('.dice-panel')).toBeVisible()
})
