import { test, expect } from '@playwright/test'
import { setup, open, openRoute, renameWorldPoint } from './helpers'

for (const touch of [false, true]) test.describe(touch ? 'touch' : 'mouse', () => {
  test.use({ hasTouch: touch })
  test(`placing one world point opens its settings and ends placement (${touch ? 'touch' : 'mouse'})`, async ({ page }, info) => {
    await page.setViewportSize({ width: touch ? 704 : 1440, height: 932 })
    const state = await setup(page)
    state.maps.push({ id: 'world', name: 'Мир', imageId: 1, imageUrl: '/test-global-world.svg', current: true, revision: 1, routes: [
    { id: 'route', name: 'Путь', color: '#b397df', playerIds: [], points: [{ id: 'start', x: .6, y: .4, name: 'Начало' }] },
    { id: 'other', name: 'Другой маршрут', color: '#99b3bd', playerIds: [], points: [{ id: 'shared', x: .2, y: .4, name: 'Общая точка', note: 'Общая заметка' }] },
    ] })
    await open(page)
    await expect(page.getByText('Загружаем изображение…', { exact: true })).toHaveCount(0)
    await openRoute(page)
    await page.getByRole('button', { name: 'Добавить точку на карту', exact: true }).click()
    const canvas = page.locator('.global-map-canvas')
    await expect(canvas).toHaveClass(/global-map-canvas--adding/)
    const image = await page.locator('.global-map-image').boundingBox()
    const activate = async (x, y) => touch ? page.touchscreen.tap(x, y) : page.mouse.click(x, y)
    await activate(image.x + image.width * .4, image.y + image.height * .7)
    await expect.poll(() => state.maps[0].routes[0].points.length).toBe(2)
    const addedId = state.maps[0].routes[0].points[1].id
    const focus = page.getByRole('complementary', { name: 'Настройки точки', exact: true })
    await expect(focus).toBeVisible()
    await expect(canvas).not.toHaveClass(/global-map-canvas--adding/)
    await expect(page.getByRole('button', { name: 'Готово', exact: true })).toHaveCount(0)
    await expect(page.locator(`[data-point-id="${addedId}"]`).first()).toHaveAttribute('aria-pressed', 'true')
    await renameWorldPoint(page, 'Новая остановка')
    await focus.getByRole('textbox', { name: 'Заметка точки', exact: true }).fill('Сразу после размещения')
    await expect.poll(() => state.maps[0].routes[0].points[1].note).toBe('Сразу после размещения')
    await info.attach(`placed-${touch ? 'touch' : 'mouse'}`, { body: await page.screenshot({ animations: 'disabled' }), contentType: 'image/png' })
    const bounds = await canvas.boundingBox()
    await activate(bounds.x + (touch ? 20 : bounds.width / 2), bounds.y + bounds.height - 40)
    expect(state.maps[0].routes[0].points).toHaveLength(2)
    await expect(focus).toHaveCount(0)
    await openRoute(page)
    await page.getByRole('button', { name: 'Добавить точку на карту', exact: true }).click()
    const marker = await page.locator('button[data-source-id="shared"]').boundingBox()
    await activate(marker.x + marker.width / 2, marker.y + marker.height / 2)
    await expect.poll(() => state.maps[0].routes[0].points.length).toBe(3)
    const visit = state.maps[0].routes[0].points[2]
    expect(visit.refId).toBe('shared')
    await expect(focus).toBeVisible()
    await expect(focus.getByRole('heading', { name: 'Общая точка', exact: true })).toBeVisible()
    await expect(focus.getByRole('button', { name: 'Открыть маршрут Путь', exact: true })).toBeVisible()
    await expect(page.locator(`button[data-point-id="${visit.id}"]`)).toHaveAttribute('aria-pressed', 'true')
    await expect(canvas).not.toHaveClass(/global-map-canvas--adding/)
    await openRoute(page)
    await page.getByRole('button', { name: 'Добавить точку на карту', exact: true }).click()
    const tail = await page.locator('button[data-source-id="shared"]').boundingBox()
    await activate(tail.x + tail.width / 2, tail.y + tail.height / 2)
    expect(state.maps[0].routes[0].points).toHaveLength(3)
    await expect(canvas).toHaveClass(/global-map-canvas--adding/)
    await canvas.focus()
    await page.keyboard.press('Escape')
    await expect(canvas).not.toHaveClass(/global-map-canvas--adding/)
    await page.reload()
    await page.locator(`button[data-source-id="${addedId}"]`).click()
    await expect(focus.getByRole('heading', { name: 'Новая остановка', exact: true })).toBeVisible()
    await expect(focus.getByRole('textbox', { name: 'Заметка точки', exact: true })).toHaveValue('Сразу после размещения')
    expect(state.maps[0].routes[0].points).toHaveLength(3)
  })
})
