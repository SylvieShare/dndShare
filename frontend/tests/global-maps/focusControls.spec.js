import { test, expect } from '@playwright/test'
import { open, openRoute, setup } from './helpers'
async function ready(page, mobile) {
  await page.setViewportSize(mobile ? { width: 430, height: 932 } : { width: 1600, height: 1000 })
  const state = await setup(page)
  state.maps.push({ id: 'world', name: 'Мир', imageId: 1, imageUrl: '/test-global-world.svg', current: true, revision: 1, routes: [{ id: 'route', name: 'Путь', color: '#b397df', playerIds: [], points: [{ id: 'a', x: .3, y: .4, name: 'Начало' }, { id: 'b', x: .7, y: .6, name: 'Конец' }] }] })
  await open(page)
  await expect(page.getByText('Загружаем изображение…', { exact: true })).toHaveCount(0)
  return state
}
for (const mobile of [false, true]) test(`compact point and route use editor headings and contextual controls ${mobile}`, async ({ page }) => {
  const state = await ready(page, mobile)
  await page.locator('button[data-source-id="a"]').click()
  const focus = page.getByRole('complementary', { name: 'Настройки точки', exact: true })
  await expect(focus.locator('.inspector-entity-heading')).toHaveCount(1)
  await expect(focus.getByRole('button', { name: 'Закрыть настройки точки', exact: true })).toHaveCount(0)
  await expect(focus.getByRole('textbox', { name: 'Название точки', exact: true })).toHaveCount(0)
  await expect(focus.getByText(/Точка \d+ из \d+/)).toHaveCount(0)
  await focus.getByRole('button', { name: 'Изменить название точки', exact: true }).click()
  await focus.getByRole('textbox', { name: 'Название точки', exact: true }).fill('Переправа')
  await page.keyboard.press('Enter')
  await expect.poll(() => state.maps[0].routes[0].points[0].name).toBe('Переправа')
  const preview = await focus.locator('.inspector-visual').boundingBox(), reference = await focus.locator('.inspector-reference').boundingBox()
  expect(reference.y - preview.y - preview.height).toBeLessThanOrEqual(10)
  await focus.getByRole('button', { name: 'Открыть маршрут Путь', exact: true }).click()
  const routeFocus = page.getByRole('complementary', { name: 'Настройки маршрута', exact: true })
  await expect(routeFocus.getByText('Игроки маршрута', { exact: true })).toHaveCount(0)
  await expect(routeFocus.getByLabel('Добавить существующую точку', { exact: true })).toHaveCount(0)
  await expect(routeFocus.getByText(/Перетащите за ручку/)).toHaveCount(0)
  await routeFocus.getByRole('button', { name: 'Изменить название маршрута', exact: true }).click()
  await routeFocus.getByRole('textbox', { name: 'Название маршрута', exact: true }).fill('Новый путь')
  await page.keyboard.press('Enter')
  await expect.poll(() => state.maps[0].routes[0].name).toBe('Новый путь')
  const last = await routeFocus.getByRole('listitem').last().boundingBox(), add = await routeFocus.getByRole('button', { name: 'Добавить точку на карту', exact: true }).boundingBox()
  expect(add.y).toBeGreaterThanOrEqual(last.y + last.height)
  await routeFocus.getByRole('button', { name: 'Цвет маршрута', exact: true }).click()
  await expect(page.locator('.base-popover').last()).toBeVisible()
  await page.keyboard.press('Escape')
  await routeFocus.getByRole('button', { name: 'Добавить точку на карту', exact: true }).click()
  await expect(page.getByRole('button', { name: 'Готово', exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'Готово', exact: true }).click()
  await expect(routeFocus).toBeVisible()
})
for (const mobile of [false, true]) test(`shared legends and session shortcut toggle lives in settings ${mobile}`, async ({ page }) => {
  await ready(page, mobile)
  const worldHint = page.locator('.global-map-controls-hint')
  await expect(worldHint).toHaveClass(/workspace-controls-hint/)
  if (mobile) await worldHint.getByRole('button', { name: 'Управление миром', exact: true }).click()
  await expect(worldHint.getByLabel('Команды управления миром', { exact: true })).toContainText('Перенос маркера')
  await page.getByRole('button', { name: 'Сюжет', exact: true }).click()
  const story = page.locator('.canvas-hotkeys')
  await expect(story).toHaveClass(/workspace-controls-hint/)
  await expect(story.getByLabel('Команды управления сюжетом', { exact: true })).toBeVisible()
  await expect(page.getByRole('button', { name: 'Горячие клавиши', exact: true })).toHaveCount(0)
  await story.getByLabel('Команды управления сюжетом', { exact: true }).click()
  await expect(story.getByRole('button', { name: 'Управление сюжетом', exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'Настройки', exact: true }).click()
  const toggle = page.getByRole('button', { name: 'Горячие клавиши', exact: true })
  await expect(toggle).toBeVisible()
  await toggle.click()
  await expect(page.getByRole('button', { name: 'Скрыть подсказки', exact: true })).toHaveAttribute('aria-pressed', 'true')
  await page.getByRole('button', { name: 'Сюжет', exact: true }).click()
  await expect(story.getByRole('button', { name: 'Управление сюжетом', exact: true })).toBeVisible()
})
