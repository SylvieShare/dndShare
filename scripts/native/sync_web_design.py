def icon_paths(node):
    for tag, attrs in node:
        if tag == "path":
            yield attrs["d"]
        elif tag == "circle":
            x, y, r = (float(attrs[k]) for k in ("cx", "cy", "r"))
            yield f"M{x-r},{y}a{r},{r} 0 1,0 {2*r},0a{r},{r} 0 1,0 {-2*r},0"
        elif tag == "line":
            yield f'M{attrs["x1"]},{attrs["y1"]}L{attrs["x2"]},{attrs["y2"]}'
        elif tag == "polyline":
            yield "M" + attrs["points"].replace(" ", "L")
        elif tag == "rect":
            x, y, w, h = (float(attrs.get(k, 0)) for k in ("x", "y", "width", "height"))
            r = min(float(attrs.get("rx", 0)), w / 2, h / 2)
            yield (f"M{x+r},{y}H{x+w-r}A{r},{r} 0 0 1 {x+w},{y+r}V{y+h-r}"
                   f"A{r},{r} 0 0 1 {x+w-r},{y+h}H{x+r}A{r},{r} 0 0 1 {x},{y+h-r}"
                   f"V{y+r}A{r},{r} 0 0 1 {x+r},{y}Z")
        else:
            raise ValueError(f"Unsupported Lucide element: {tag}")


def outputs():
    tokens = (FRONTEND / "node_modules/@sylvieshare/share-ui/src/styles/tokens.css").read_text()
    tokens += (FRONTEND / "src/app/design-tokens.css").read_text()
    tokens += (FRONTEND / "src/app/theme.css").read_text()
    declarations = dict(re.findall(r"--([\w-]+):\s*(#[\da-fA-F]{3,8}|var\(--[\w-]+\));", tokens))
    def resolve(name, seen=()):
        if name in seen: raise ValueError("Cyclic palette alias: " + name)
        value = declarations[name]
        return resolve(value[6:-1], (*seen, name)) if value.startswith("var(--") else value
    values = {name: resolve(name) for name in COLORS.values()}
    lines = ["// Generated by scripts/native/sync_web_design.py; edit the web tokens, then regenerate.",
             "package ru.dndshare.client.ui.designsystem", "", "import androidx.compose.ui.graphics.Color", "",
             "object WebPalette {"]
    for name, token in COLORS.items():
        value = values[token].lstrip("#")
        if len(value) == 3:
            value = "".join(c * 2 for c in value)
        lines.append(f"    val {name} = Color(0xFF{value.upper()})")
    for name, token, base, channel in [("Border", "border", "White", "255"),
                                      ("BorderStrong", "border-strong", "White", "255"),
                                      ("Scrim", "scrim", "Black", "0")]:
        alpha = re.findall(r"--" + token + r":\s*rgb\(" + " ".join([channel] * 3) + r" / ([\d.]+)%\);", tokens)
        if not alpha:
            raise ValueError(f"Unsupported web alpha color: --{token}")
        lines.append(f"    val {name} = Color.{base}.copy(alpha = {float(alpha[-1]) / 100:.2f}f)")
    lines += ["}", ""]
    yield NATIVE / "kotlin/ru/dndshare/client/ui/designsystem/WebPalette.kt", "\n".join(lines)
    yield NATIVE / "res/values/share_colors.xml", (
        '<!-- Generated by scripts/native/sync_web_design.py -->\n<resources>\n'
        f'    <color name="share_background">{values["bg"]}</color>\n'
        f'    <color name="share_accent_soft">{values["accent-soft"]}</color>\n'
        '</resources>\n'
    )
    package = FRONTEND / "node_modules/@lucide/vue"
    for slug in ICONS.values():
        source = (package / f"dist/esm/icons/{slug}.mjs").read_text()
        data = re.search(r"const __iconData = (\{.*?\n\});", source, re.S).group(1)
        data = re.sub(r"(\b\w+):", r'"\1":', data)
        paths = icon_paths(json.loads(data)["node"])
        xml = ['<!-- Generated from @lucide/vue; license: assets/licenses/lucide.txt -->',
               '<vector xmlns:android="http://schemas.android.com/apk/res/android"',
               '    android:width="24dp" android:height="24dp" android:viewportWidth="24" android:viewportHeight="24">']
        for path in paths:
            xml += ['    <path android:fillColor="#00000000" android:strokeColor="#FFFFFFFF"',
                    '        android:strokeWidth="1.8" android:strokeLineCap="round" android:strokeLineJoin="round"',
                    '        android:pathData=' + quoteattr(path) + ' />']
        yield NATIVE / f"res/drawable/lucide_{slug.replace('-', '_')}.xml", "\n".join([*xml, "</vector>", ""])
    yield NATIVE / "assets/licenses/lucide.txt", (package / "LICENSE").read_text()
    for filename in ("tab-stats.svg", "tab-weapons.svg", "tab-magic.svg", "tab-skills.svg", "tab-personality.svg", "container-box.svg", "edit-note.svg", "hp-pulse.svg", "shield.svg", "initiative.svg", "speed.svg", "prof-bonus.svg"):
        yield NATIVE / "assets/character-sheet" / filename, (FRONTEND / "public/static" / filename).read_text()


def dice_shapes():
    source = (FRONTEND / "src/shared/ui/SystemDie.vue").read_text()
    raw = re.search(r"const SHAPES = (\{.*?\n\})", source, re.S).group(1)
    raw = re.sub(r"(\b\w+):", r'"\1":', raw).replace("'", '"')
    raw = re.sub(r",\s*([}\]])", r"\1", raw)
    shapes = json.loads(raw)
    lines = ["// Generated from frontend/src/shared/ui/SystemDie.vue. Do not edit.",
             "package ru.dndshare.client.ui.designsystem", "",
             "internal data class ShareDieShape(val path: String, val liquidY: Float, val shineY: Float, val textY: Float, val fontSizes: List<Float>)",
             "internal val shareDieShapes = mapOf("]
    for key, row in shapes.items():
        sizes = ", ".join(str(value) + "f" for value in row["fontSizes"])
        lines.append(f'    {key[1:]} to ShareDieShape({json.dumps(row["path"])}, {row["liquidY"]}f, {row["shineY"]}f, {row["textY"]}f, listOf({sizes})),')
    lines.extend([")", ""])
    return "\n".join(lines)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="Fail if committed native resources differ from web")
    args = parser.parse_args()
    stale = []
    generated = list(outputs()) + [(NATIVE / "kotlin/ru/dndshare/client/ui/designsystem/DieShapes.kt", dice_shapes()), (NATIVE / "kotlin/ru/dndshare/client/ui/designsystem/WebEffectSpec.kt", render_effect_specs(ROOT))]
    for path, content in generated:
        if args.check:
            if not path.exists() or path.read_text() != content:
                stale.append(str(path.relative_to(ROOT)))
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content)
    if stale:
        raise SystemExit("Regenerate Android web design resources:\n" + "\n".join(stale))
    print("Android palette and Lucide resources match the web" if args.check else "Android web design resources generated")


if __name__ == "__main__":
    main()
