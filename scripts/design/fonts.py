#!/usr/bin/env python3
"""Lossless offline web fonts from the Android design system (Python >= 3.11).

Generate from the repository root with an isolated, hash-locked toolchain:
  python3 -m venv build/dev-tools/fonts
  build/dev-tools/fonts/bin/python -m pip install --require-hashes \
      -r scripts/design/requirements-fonts.lock
  build/dev-tools/fonts/bin/python scripts/design/fonts.py --generate
Verify without third-party packages:
  python3 scripts/design/fonts.py --check
  python3 -m unittest discover -s scripts/design -p 'test_fonts.py'

Import '@/app/fonts.css' once in main.js alongside the existing theme imports.
No subsetting, instancing, timestamp rewriting, or metric overrides are used.
"""

import argparse
import hashlib
import json
from pathlib import Path
import sys
import tempfile

ROOT = Path(__file__).resolve().parents[2]
NATIVE = Path('native/androidApp')
PUBLIC = Path('frontend/public/static/fonts')
CSS = Path('frontend/src/app/fonts.css')
SCRIPT = Path('scripts/design/fonts.py')
LOCK = Path('scripts/design/requirements-fonts.lock')
MANIFEST = PUBLIC / 'manifest.json'
VERSIONS = {'fonttools': '4.67.0', 'brotli': '1.2.1'}
FACES = (
    ('cormorant_garamond.ttf', 'Cormorant Garamond', 'normal', '500 700',
     'cormorantgaramond-OFL.txt'),
    ('literata.ttf', 'Literata', 'normal', '400 700', 'literata-OFL.txt'),
    ('literata_italic.ttf', 'Literata', 'italic', '400 700', 'literata-OFL.txt'),
)


def require(condition, message):
    if not condition:
        raise ValueError(message)


def record(root, relative):
    data = (root / relative).read_bytes()
    return {'file': relative.as_posix(), 'sha256': hashlib.sha256(data).hexdigest()}


def output_name(source, digest):
    """Immutable asset URL derived from the SHA-256 of compressed WOFF2 bytes."""
    require(len(digest) == 64 and all(c in '0123456789abcdef' for c in digest),
            'Invalid output SHA-256')
    return f"{Path(source).stem.replace('_', '-')}-{digest[:12]}.woff2"


def render_css(output_hashes):
    blocks = ['/* Generated by scripts/design/fonts.py; retain existing display/prose stacks. */']
    for source, family, style, weight, _ in FACES:
        blocks.append('\n'.join([
            '@font-face {', f'  font-family: "{family}";',
            f'  src: url("/static/fonts/{output_name(source, output_hashes[source])}") format("woff2");',
            f'  font-style: {style};', f'  font-weight: {weight};',
            '  font-display: swap;', '}',
        ]))
    return ('\n\n'.join(blocks) + '\n').encode('utf-8')


def inputs(root):
    entries = json.loads((root / NATIVE / 'font-sources.json').read_text('utf-8'))
    names = [entry['file'] for entry in entries]
    require(len(names) == len(set(names)) and set(names) == {f[0] for f in FACES},
            'font-sources.json must match the three offline web faces')
    sources = {entry['file']: entry for entry in entries}
    fonts = []
    for filename, family, style, weight, license_name in FACES:
        source = record(root, NATIVE / 'src/main/res/font' / filename)
        require(source['sha256'] == sources[filename]['sha256'],
                f'Source SHA-256 differs from font-sources.json: {filename}')
        source['url'] = sources[filename]['source']
        fonts.append({'family': family, 'style': style, 'weight': weight,
                      'source': source, 'license': license_name})
    return fonts


def manifest(root, output_hashes):
    fonts = inputs(root)
    for face in fonts:
        source = Path(face['source']['file']).name
        relative = PUBLIC / output_name(source, output_hashes[source])
        face['output'] = record(root, relative)
        face['output']['bytes'] = (root / relative).stat().st_size
    licenses = []
    for name in sorted({face[-1] for face in FACES}):
        licenses.append({
            'source': record(root, NATIVE / 'src/main/assets/licenses' / name),
            'output': record(root, PUBLIC / name),
        })
    return {
        'schema': 1,
        'generator': {'script': record(root, SCRIPT), 'requirements': record(root, LOCK),
                      'packages': VERSIONS,
                      'command': 'build/dev-tools/fonts/bin/python scripts/design/fonts.py --generate'},
        'source_manifest': record(root, NATIVE / 'font-sources.json'),
        'css': record(root, CSS), 'fonts': fonts, 'licenses': licenses,
    }


def check(root=ROOT):
    saved = json.loads((root / MANIFEST).read_text('utf-8'))
    output_hashes = {Path(face['source']['file']).name: face['output']['sha256']
                     for face in saved['fonts']}
    expected = manifest(root, output_hashes)
    require((root / CSS).read_bytes() == render_css(output_hashes), 'fonts.css is stale')
    for license_record in expected['licenses']:
        require(license_record['source']['sha256'] == license_record['output']['sha256'],
                f"Public OFL differs from Android: {license_record['output']['file']}")
    require(saved == expected, 'Font manifest/assets are stale or modified; regenerate with the locked toolchain')
    require({p.name for p in (root / PUBLIC).glob('*.woff2')} ==
            {Path(face['output']['file']).name for face in expected['fonts']},
            'Stale WOFF2 files; regenerate with the locked toolchain')


def compare_fonts(source, output):
    """Check actual decoded fonts, including all cmaps, axes and layout/metrics."""
    require(source.getGlyphOrder() == output.getGlyphOrder(), 'Glyph order changed')
    cmaps = lambda font: [{key: value for key, value in table.__dict__.items() if key != 'ttFont'}
                          for table in font['cmap'].tables]
    # Decompile every cmap before comparing (including non-default/UVS maps).
    for font in (source, output):
        for table in font['cmap'].tables:
            table.ensureDecompiled()
    require(cmaps(source) == cmaps(output), 'Character maps changed')
    axes = lambda font: [axis.__dict__ for axis in font['fvar'].axes]
    require(axes(source) == axes(output), 'Variable axes changed')
    require(source['hmtx'].metrics == output['hmtx'].metrics, 'Advance widths changed')
    for name in source.getGlyphOrder():
        require(source['glyf'][name].getCoordinates(source['glyf']) ==
                output['glyf'][name].getCoordinates(output['glyf']),
                f'Glyph outlines changed: {name}')
    require(set(source.keys()) == set(output.keys()), 'Font tables changed')
    # WOFF2 transforms glyf/loca losslessly but may normalize their encoding.
    # head also contains the resulting checksum, loca format and transform flag.
    for tag in set(source.keys()) - {'GlyphOrder', 'glyf', 'loca', 'head'}:
        require(source.getTableData(tag) == output.getTableData(tag),
                f'Layout/variation/metric table changed: {tag}')
    for key in ('unitsPerEm', 'xMin', 'yMin', 'xMax', 'yMax', 'created', 'modified'):
        require(getattr(source['head'], key) == getattr(output['head'], key),
                f'Font header changed: {key}')


def generate(root=ROOT):
    # Lazy imports keep --check usable with a bare stdlib interpreter.
    from importlib.metadata import version
    from fontTools.ttLib import TTFont
    from fontTools.ttLib.woff2 import compress

    for package, pinned in VERSIONS.items():
        require(version(package) == pinned, f'Install {LOCK}: expected {package}=={pinned}')
    fonts = inputs(root)
    output_hashes = {}
    # Validate all converted fonts before replacing any committed output.
    with tempfile.TemporaryDirectory(prefix='dndshare-fonts-') as temporary:
        staging = Path(temporary)
        for face in fonts:
            source = root / face['source']['file']
            target = staging / source.with_suffix('.woff2').name
            compress(source, target)
            output_hashes[source.name] = hashlib.sha256(target.read_bytes()).hexdigest()
            target = target.rename(staging / output_name(source.name, output_hashes[source.name]))
            with TTFont(source, recalcTimestamp=False) as original, TTFont(target, recalcTimestamp=False) as web:
                compare_fonts(original, web)
                print(f'{target.name}: {source.stat().st_size} -> {target.stat().st_size} bytes; '
                      f'{len(web.getBestCmap())} codepoints; '
                      f'axes {[(a.axisTag, a.minValue, a.maxValue) for a in web["fvar"].axes]}')
        (root / PUBLIC).mkdir(parents=True, exist_ok=True)
        for target in staging.iterdir():
            (root / PUBLIC / target.name).write_bytes(target.read_bytes())
    wanted = {output_name(source, digest) for source, digest in output_hashes.items()}
    for source in output_hashes:
        stem = Path(source).stem.replace('_', '-')
        old_files = [root / PUBLIC / f'{stem}.woff2']
        old_files.extend((root / PUBLIC).glob(f'{stem}-{"[0-9a-f]" * 12}.woff2'))
        for old in old_files:
            if old.name not in wanted:
                old.unlink(missing_ok=True)
    for name in sorted({face[-1] for face in FACES}):
        (root / PUBLIC / name).write_bytes((root / NATIVE / 'src/main/assets/licenses' / name).read_bytes())
    (root / CSS).parent.mkdir(parents=True, exist_ok=True)
    (root / CSS).write_bytes(render_css(output_hashes))
    (root / MANIFEST).write_text(json.dumps(manifest(root, output_hashes), indent=2, ensure_ascii=False) + '\n', encoding='utf-8')
    check(root)


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    mode = parser.add_mutually_exclusive_group(required=True)
    mode.add_argument('--check', action='store_true', help='Verify source/output hashes with stdlib only')
    mode.add_argument('--generate', action='store_true', help='Generate lossless WOFF2 with the locked dependencies')
    arguments = parser.parse_args()
    try:
        (check if arguments.check else generate)()
    except (OSError, ValueError, KeyError, TypeError, ImportError) as error:
        print(f'Fonts: {error}', file=sys.stderr)
        return 1
    print('Offline web fonts verified.')
    return 0


if __name__ == '__main__':
    sys.exit(main())
