"""Generate platform adapters; design values only live in design/tokens.json."""
import json
from token_model import digest, literal, media_queries, pascal

CSS = 'frontend/src/app/design-tokens.css'
JS = 'frontend/src/app/design-tokens.js'
KOTLIN = 'native/designSystem/src/main/kotlin/ru/dndshare/designsystem/DesignTokens.kt'


def render(data, source_hash):
    header = f'Generated by scripts/design/tokens.py; source sha256 {source_hash}'
    css = [f'/* {header} */', ':root {']
    css += [f'  --{name}: {value};' for name, value in data['colors'].items()]
    for group in ['layout', 'spacing', 'radius', 'collection', 'canvas', 'list', 'motion']:
        for name, value in data[group].items():
            unit = '' if group == 'canvas' and name == 'opacity' else 'ms' if group == 'motion' and name != 'distance' else 'px'
            css.append(f'  --{group}-{name}: {literal(value)}{unit};')
    for name, role in data['typography'].items():
        family = {'ui': 'ui', 'display': 'display', 'prose': 'prose'}[role['family']]
        css += [f'  --type-{name}-family: var(--font-{family});',
                f'  --type-{name}-size: {literal(role["size"])}px;',
                f'  --type-{name}-line-height: {literal(role["lineHeight"])}px;',
                f'  --type-{name}-weight: {role["weight"]};',
                f'  --type-{name}-tracking: {literal(role["tracking"])}px;']
    css += [
        '  --header-h: 0px;', '  --app-sidebar-w: var(--layout-sidebar-collapsed);',
        '  --sidebar-collapsed-w: var(--layout-sidebar-collapsed);',
        '  --sidebar-expanded-w: var(--layout-sidebar-expanded);',
        '  --share-sidebar-collapsed-w: var(--layout-sidebar-collapsed);',
        '  --share-sidebar-expanded-w: var(--layout-sidebar-expanded);',
        '  --content-max: var(--layout-content-max);',
        '  --r-xs: var(--radius-xs);', '  --r-sm: var(--radius-small);',
        '  --r-md: var(--radius-medium);', '  --r-lg: var(--radius-large);',
        '  --app-canvas-dot-size: var(--canvas-step);',
        '  --app-canvas-dot-color: color-mix(in srgb, var(--border-strong) calc(var(--canvas-opacity) * 100%), transparent);',
        '  --app-canvas-pattern: radial-gradient(circle, var(--app-canvas-dot-color) var(--canvas-radius), transparent var(--canvas-radius));',
        '}',
        f'@media {media_queries(data)["--ui-compact"]} {{',
        '  :root { --header-h: var(--layout-header); --app-sidebar-w: 0px; }', '}',
        f'@media {media_queries(data)["--ui-phone"]} {{',
        '  :root { --app-sidebar-w: 0px; }', '}', '',
    ]
    js = [f'// {header}', f'export const layoutTokens = Object.freeze({json.dumps(data["layout"], indent=2)});',
          f'export const designMediaQueries = Object.freeze({json.dumps(media_queries(data), indent=2)});', '']
    kt = [f'// {header}', 'package ru.dndshare.designsystem', '',
          'import androidx.compose.ui.unit.dp', 'import androidx.compose.ui.unit.sp',
          'import androidx.compose.ui.unit.TextUnit', 'import androidx.compose.ui.text.font.FontWeight', '',
          'enum class DesignFont { Display, Prose, Ui }',
          'data class DesignType(val size: TextUnit, val lineHeight: TextUnit, val tracking: TextUnit, val weight: FontWeight, val family: DesignFont)', '',
          'object DesignTokens {']
    for group in ['layout', 'spacing', 'radius', 'collection', 'canvas', 'list', 'motion']:
        kt.append(f'    object {pascal(group)} {{')
        for name, value in data[group].items():
            unit = 'f' if group == 'canvas' and name == 'opacity' else '' if group == 'motion' and name != 'distance' else '.dp'
            kt.append(f'        val {pascal(name)} = {literal(value)}{unit}')
        kt.append('    }')
    kt.append('    object Typography {')
    for name, role in data['typography'].items():
        kt.append(f'        val {pascal(name)} = DesignType({literal(role["size"])}.sp, '
                  f'{literal(role["lineHeight"])}.sp, {literal(role["tracking"])}.sp, FontWeight({role["weight"]}), DesignFont.{pascal(role["family"])})')
    kt += ['    }', '}', '']
    return {CSS: '\n'.join(css), JS: '\n'.join(js), KOTLIN: '\n'.join(kt)}


def manifest(source_hash, outputs):
    return json.dumps({'schemaVersion': 1, 'source': 'design/tokens.json', 'sourceSha256': source_hash,
                       'outputs': {name: digest(content.encode()) for name, content in outputs.items()}}, indent=2) + '\n'
