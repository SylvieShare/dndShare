def patch_stages(id,data):
    if id == 737:
        first = {**data['rolls'][0], 'label':'Первоначальный захват', 'save_ability':'str','save_effect':'negate','save_condition':'При провале цель также опутана.'}
        second = {**first, 'label':'Сдавливание захваченной цели','save_effect':'half','save_condition':'По отдельному действию заклинателя.'}
        data['rolls']=[first,second]; data['damage']['save_manual']=True
        return 'Захват и сдавливание разделены: успех первого спасброска отменяет урон, успех второго делит его пополам. Опутывание и освобождение проверкой Силы пока вручную.'
    if id in SAVES:
        data.setdefault('damage',{})['save_manual']=True
        for index,ability,result,condition in SAVES[id]: data['rolls'][index].update(save_ability=ability,save_effect=result,save_condition=condition)
        if id==917:
            data['damage']['range_attack']=False
            return 'Спасбросок привязан ко вторичному взрыву. Бросок атаки выполняется оружием, не заклинательной характеристикой. Замена урона оружия и половина при промахе пока вручную.'
        return 'Спасброски привязаны к отдельным этапам с правильной характеристикой и результатом успеха. Последовательность этапов, повторения и дополнительные состояния проверяются участниками.'
    if id==596:
        data['damage'].update(save_manual=True,scaling='none')
        return 'Урон кольца не зависит от спасброска; отдельно объявляется спасбросок Силы против отталкивания. Запас 2 + 2 за круг колец и их расход пока вручную.'
    if id in [1305,965]:
        data['damage']['scaling']='none'
        return 'Урон одного снаряда поддержан и не увеличивается от круга. Круг увеличивает запас снарядов; его отдельный ресурс и расход требуют дополнительной механики.'
    return None
