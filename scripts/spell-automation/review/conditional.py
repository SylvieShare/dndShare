def patch_conditional(id,data):
    if id not in ROWS:return None
    assert not data.get('rolls'), f'Conditional rolls already exist: {id}'
    data['rolls']=ROWS[id]
    data.setdefault('damage',{})['save_manual']=True
    if id in [1222,1119]:data['damage']['range_attack']=True
    if id in [867,1339]:data['damage']['save_ability']='wis'
    return 'Добавлены отдельные формулы для описанных этапов; условный урон не применяется автоматически при сотворении. '+NOTES.get(id,'Порядок этапов, условия попадания в область, дополнительные состояния и их окончание контролируются участниками.')
